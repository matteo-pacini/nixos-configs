def keep_victims(names, keep, protected):
    """Our files to delete, oldest first, so that `keep` remain.

    Files not matching TUNE_FILE are never counted or returned; protected
    names (playing, queued) are counted but never returned."""
    ours = sorted(n for n in names if TUNE_FILE.match(n))
    excess = len(ours) - keep
    out = []
    for n in ours:
        if excess <= 0:
            break
        if n in protected:
            continue
        out.append(n)
        excess -= 1
    return out


def levels_db(samples, rate=DECODE_RATE, window=LEVEL_WINDOW):
    """RMS level in dBFS of each window of 16-bit mono samples."""
    n = max(1, int(rate * window))
    out = []
    for i in range(0, len(samples), n):
        chunk = samples[i:i + n]
        power = sum(s * s for s in chunk) / len(chunk)
        out.append(-120.0 if power <= 0 else 10 * math.log10(power / (32768.0 ** 2)))
    return out


def quiet_mid_run(levels, window=LEVEL_WINDOW):
    """Seconds of the longest run under QUIET_DB that does not reach the end."""
    worst = run = 0
    for v in levels:
        if v < QUIET_DB:
            run += 1
        else:
            worst = max(worst, run)
            run = 0
    return worst * window


def wave_bars(samples, bars=WAVE_BARS):
    """Mean absolute level of `bars` equal slices, scaled to the loudest."""
    if not samples:
        return [0.0] * bars
    out = []
    n = len(samples)
    for b in range(bars):
        chunk = samples[b * n // bars:(b + 1) * n // bars] or samples[min(n - 1, b * n // bars):][:1]
        out.append(sum(abs(s) for s in chunk) / len(chunk))
    top = max(out)
    return [round(v / top, 3) if top else 0.0 for v in out]


def parse_vulkaninfo(text):
    """Devices of `vulkaninfo --summary`, in its order: dicts of vendor,
    device (lower-case hex), type, name, uuid."""
    devs, cur = [], None
    in_devices = False
    for line in text.splitlines():
        if line.strip() == "Devices:":
            in_devices = True
            continue
        if not in_devices:
            continue
        if re.match(r"^GPU\d+:\s*$", line):
            cur = {}
            devs.append(cur)
            continue
        m = re.match(r"^\s+(\w+)\s*=\s*(.*?)\s*$", line)
        if m and cur is not None:
            cur[m.group(1)] = m.group(2)
    return [{"vendor": d.get("vendorID", "").lower(), "device": d.get("deviceID", "").lower(),
             "type": d.get("deviceType", ""), "name": d.get("deviceName", ""),
             "uuid": d.get("deviceUUID", "")} for d in devs]


def ggml_devices(devs):
    """The devices ggml's Vulkan backend numbers, in its order: discrete and
    integrated GPUs only, the first of any sharing a device UUID."""
    out, seen = [], set()
    for d in devs:
        if d["type"] not in ("PHYSICAL_DEVICE_TYPE_DISCRETE_GPU", "PHYSICAL_DEVICE_TYPE_INTEGRATED_GPU"):
            continue
        if d["uuid"] and d["uuid"] in seen:
            continue
        seen.add(d["uuid"])
        out.append(d)
    return out


def resolve_device(text, vendor, device):
    """(index, name) of the wanted device, or (None, what was found)."""
    vendor, device = vendor.lower(), device.lower()
    gpus = ggml_devices(parse_vulkaninfo(text))
    for i, d in enumerate(gpus):
        if d["vendor"] == vendor and d["device"] == device:
            return i, d["name"]
    if not gpus:
        return None, "found no Vulkan GPU"
    names = "; ".join(d["name"] for d in gpus)
    return None, f"found {len(gpus)} other Vulkan GPU{'s' if len(gpus) > 1 else ''}: {names}"


def confirm_device(lines, index, name):
    """None when the server's ggml_vulkan line for `index` names `name`, else
    what it said instead."""
    listed = {}
    for line in lines:
        m = GGML_DEVICE.match(line)
        if m:
            listed[int(m.group(1))] = m.group(2)
    if index in listed and listed[index].startswith(name):
        return None
    if index in listed:
        return f"the server's Vulkan{index} is {listed[index].split(' | ')[0]}"
    return f"the server listed no Vulkan{index}"


def game_running(clients, pattern):
    if not pattern:
        return False
    rx = re.compile(pattern)
    return any(isinstance(c, dict) and isinstance(c.get("class"), str) and rx.fullmatch(c["class"])
               for c in clients if isinstance(clients, list))


def mem_available(text):
    m = re.search(r"^MemAvailable:\s+(\d+) kB", text, re.M)
    return int(m.group(1)) * 1024 if m else None


def multipart_audio(body):
    """The first audio part of ace-server's multipart/mixed synth result."""
    if not body.startswith(b"--"):
        raise ValueError("not multipart")
    boundary = body[:body.index(b"\r\n")]
    for part in body.split(b"\r\n" + boundary):
        part = part[len(boundary):] if part.startswith(boundary) else part
        head, sep, data = part.partition(b"\r\n\r\n")
        if sep and b"content-type: audio/" in head.lower():
            return data
    raise ValueError("no audio part")


def median(values):
    """The median of `values`, None for an empty list."""
    if not values:
        return None
    s = sorted(values)
    mid = len(s) // 2
    return float(s[mid]) if len(s) % 2 else (s[mid - 1] + s[mid]) / 2


def add_timing(values, seconds):
    """`values` with `seconds` appended, the last TIMINGS_KEPT only."""
    return (list(values) + [round(seconds, 1)])[-TIMINGS_KEPT:]


def read_timings(raw):
    """{"writing": [...], "rendering": [...]} from state.json's object;
    anything malformed reads as no timings."""
    out = {}
    for stage in STAGES:
        v = raw.get(stage) if isinstance(raw, dict) else None
        ok = isinstance(v, list) and all(isinstance(x, (int, float)) and not isinstance(x, bool)
                                         and math.isfinite(x) and x >= 0 for x in v)
        out[stage] = list(v)[-TIMINGS_KEPT:] if ok else []
    return out


def expect_view(timings):
    """The snapshot's "expect": both medians, or None until a tune is timed."""
    if not all(timings[s] for s in STAGES):
        return None
    return {f"{s}_s": median(timings[s]) for s in STAGES}


def queue_entries(ready, next_kept):
    """What "next" would play, in order: the queued tunes, or the next kept
    one when none is queued."""
    return list(ready) if ready else ([next_kept] if next_kept else [])


def file_stem(t):
    """A tune's file name without ".mp3": its name until the file is read."""
    return os.path.basename(t["path"])[:-4]


def names_tune(t, name):
    """Whether a command's `name` (None when it gave none) names tune `t`:
    its name now, or its file name, which it showed before its file was
    read."""
    return name is None or name in (t.get("name"), file_stem(t))


def scrappable(path, music):
    """True for a tune file named as ours directly in a genre folder of
    `music`."""
    genre_dir = os.path.dirname(path)
    return (bool(TUNE_FILE.match(os.path.basename(path)))
            and os.path.dirname(genre_dir) == music.rstrip("/") and genre_dir != music)


def need_bytes(files, present):
    """Bytes still to download, given {name: bytes on disk (final or part)}."""
    return sum(max(0, f["bytes"] - present.get(f["name"], 0)) for f in files)


