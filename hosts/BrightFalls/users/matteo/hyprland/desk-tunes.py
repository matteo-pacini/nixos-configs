    # -- download ------------------------------------------------------------

    def cmd_download(self):
        if self.dl_cancel or self.setup == "ready":
            return
        cancel = threading.Event()
        self.dl_cancel = cancel
        self.dl = {"file": 1, "files": len(self.model["files"]),
                   "name": ROLE_WORDS[self.model["files"][0]["role"]], "done": 0,
                   "total": sum(f["bytes"] for f in self.model["files"]), "rate": 0, "error": None}
        self.check_setup()
        self.changed()

        def progress(i, f, done, total, rate):
            self.results.put((self.download_progress, (True, (cancel, i, f, done, total, rate))))
            try:
                os.write(self.wake_w, b"x")
            except BlockingIOError:
                pass

        def run():
            with self.dl_lock:
                return download(self.model["files"], self.models_dir, self.model["base_url"],
                                self.model["revision"], cancel, progress)
        self.in_thread(run, lambda ok, value: self.download_done(cancel, ok, value))

    def download_progress(self, ok, value):
        cancel, i, f, done, total, rate = value
        if cancel is not self.dl_cancel:
            return
        self.dl.update({"file": i, "name": ROLE_WORDS[f["role"]], "done": done, "total": total,
                        "rate": rate})
        wait = self.dl_last_sent + DOWNLOAD_GAP - time.monotonic()
        if wait <= 0:
            self.dl_last_sent = time.monotonic()
            self.changed()
        elif "download_flush" not in self.timers:
            self.set_timer("download_flush", wait, self.download_flush)

    def download_flush(self):
        self.dl_last_sent = time.monotonic()
        self.changed()

    def download_done(self, cancel, ok, value):
        if cancel is not self.dl_cancel:
            return
        self.dl_cancel = None
        self.cancel_timer("download_flush")
        if not ok:
            text = str(value) if isinstance(value, DownloadError) else f"download failed: {value}"
            self.dl = dict(self.dl, error=text, rate=0)
        else:
            self.dl = None
        self.check_setup()
        self.changed()
        self.maybe_compose()

    def cmd_cancel_download(self):
        if not self.dl_cancel:
            return
        self.dl_cancel.set()
        self.dl_cancel = None
        self.dl = None
        self.cancel_timer("download_flush")
        self.check_setup()
        self.changed()

