    def ram(self):
        free = None
        try:
            with open(getattr(self.args, "test_meminfo", None) or "/proc/meminfo") as f:
                free = mem_available(f.read())
        except OSError:
            pass
        used = None
        s = self.server
        if s:
            used = 0
            try:
                with open(f"/proc/{s['child'].proc.pid}/status") as f:
                    m = re.search(r"^VmRSS:\s+(\d+) kB", f.read(), re.M)
                    used = int(m.group(1)) * 1024 if m else 0
            except OSError:
                pass
            mem = self.device_mem()
            if mem is not None and s.get("base_mem") is not None:
                used += max(0, mem - s["base_mem"])
        return used, free

    def device_mem(self):
        root = getattr(self.args, "test_sysfs", None) or "/sys"
        base = os.path.join(root, "class", "drm")
        want = (self.cfg["device"]["vendor"].lower(), self.cfg["device"]["device"].lower())
        try:
            cards = sorted(n for n in os.listdir(base) if re.fullmatch(r"card\d+", n))
        except OSError:
            return None
        for card in cards:
            dev = os.path.join(base, card, "device")
            try:
                ids = tuple(open(os.path.join(dev, k)).read().strip().lower() for k in ("vendor", "device"))
                if ids != want:
                    continue
                return sum(int(open(os.path.join(dev, k)).read()) for k in
                           ("mem_info_vram_used", "mem_info_gtt_used"))
            except (OSError, ValueError):
                continue
        return None

