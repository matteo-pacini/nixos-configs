    # -- editing genres ------------------------------------------------------

    def genres_tmp(self):
        return os.path.join(os.path.dirname(self.genres_file),
                            "." + os.path.basename(self.genres_file) + ".new")

    def genres_on_disk(self):
        """(the file's JSON, its parsed genres, its text), read now, so an
        edit by hand since the last read is kept; ValueError saying why the
        file cannot be edited."""
        try:
            with open(self.genres_file, encoding="utf-8") as f:
                text = f.read()
        except FileNotFoundError:
            raise ValueError("the genres file is missing")
        except (OSError, UnicodeDecodeError) as e:
            raise ValueError(f"the genres file cannot be read ({getattr(e, 'strerror', None) or e})")
        try:
            genres = parse_genres(text)
        except ValueError as e:
            raise ValueError(f"the genres file has a mistake ({e})")
        return json.loads(text), genres, text

    def write_genres(self, doc, old_text):
        """Replace the genres file with `doc` laid out as format_genres does,
        unless that is its text already; the selected genre takes the new
        values. Raises OSError."""
        text = format_genres(doc)
        if text != old_text:
            path, tmp = self.genres_file, self.genres_tmp()
            mode = stat.S_IMODE(os.stat(path).st_mode)
            # Beside it and renamed over it, so a crash leaves the old file or
            # the new one, and a reader never sees half of it.
            try:
                with open(tmp, "wb", opener=lambda p, flags: os.open(p, flags, mode)) as f:
                    os.fchmod(f.fileno(), mode)
                    f.write(text.encode())
                    f.flush()
                    os.fsync(f.fileno())
                os.replace(tmp, path)
            except OSError:
                try:
                    os.unlink(tmp)
                except OSError:
                    pass
                raise
            # The file is replaced by now; a failure here only weakens the
            # rename's durability across a crash, so the save stands.
            try:
                dfd = os.open(os.path.dirname(path), os.O_RDONLY)
                try:
                    os.fsync(dfd)
                finally:
                    os.close(dfd)
            except OSError as e:
                say(f"cannot sync the genres file's folder: {e.strerror}")
        self.read_genres()
        if self.genre:
            self.genre = self.genre_by_id(self.genre["id"]) or self.genre

    def genre_by_id(self, gid):
        return next((g for g in self.genres if g["id"] == gid), None)

    def genre_get(self, gid):
        self.read_genres()
        g = self.genre_by_id(gid)
        if g is None:
            return refused(None, GENRE_GONE)
        return dict({k: g[k] for k in EDIT_KEYS}, event="genre", id=g["id"])

    def genre_save(self, gid, fields, base=None):
        try:
            doc, genres, text = self.genres_on_disk()
        except ValueError as e:
            return refused(None, f"Nothing was saved: {e}.")
        on_disk = next((g for g in genres if g["id"] == gid), None) if gid is not None else None
        if gid is not None and on_disk is None:
            return refused(None, GENRE_GONE)
        if on_disk and base is not None and base != {k: on_disk[k] for k in EDIT_KEYS}:
            return refused(None, f"{on_disk['name']} was changed in the file since you opened it.")
        bad = field_error(fields, genres, gid)
        if bad:
            return refused(*bad)
        moved = renamed = None
        if gid is None:
            gid = new_genre_id(fields["name"], {g["id"] for g in genres})
            doc["genres"].append(dict(id=gid, **fields))
        else:
            raw = next(g for g in doc["genres"] if g["id"] == gid)
            if raw["name"] != fields["name"]:
                renamed = {"from": raw["name"], "to": fields["name"]}
                old, new = (os.path.join(self.music, n) for n in (raw["name"], fields["name"]))
                if os.path.lexists(new):
                    return refused("name", f"A folder called {fields['name']} already exists "
                                           "in ~/Music/Tunes.")
                if os.path.isdir(old):
                    try:
                        os.rename(old, new)
                    except OSError as e:
                        return refused(None, f"Nothing was saved: its folder could not be moved "
                                             f"({e.strerror}).")
                    moved = (old, new)
            raw.update(fields)
        try:
            self.write_genres(doc, text)
        except OSError as e:
            if moved:
                try:
                    os.rename(moved[1], moved[0])
                except OSError as e2:
                    say(f"cannot move a genre's folder back: {e2.strerror}")
            return refused(None, f"Nothing was saved: {e.strerror}.")
        if moved:
            self.follow_rename(*moved)
        return {"event": "genre_result", "ok": True, "id": gid, "renamed": renamed}

    def genre_delete(self, gid):
        try:
            doc, genres, text = self.genres_on_disk()
        except ValueError as e:
            return refused(None, f"Nothing was deleted: {e}.")
        if not any(g["id"] == gid for g in genres):
            return refused(None, GENRE_GONE)
        if len(genres) == 1:
            return refused(None, "The last genre cannot be deleted.")
        doc["genres"] = [g for g in doc["genres"] if g["id"] != gid]
        try:
            self.write_genres(doc, text)
        except OSError as e:
            return refused(None, f"Nothing was deleted: {e.strerror}.")
        if self.genre and self.genre["id"] == gid:
            if self.job and self.job["stage"] == "finish":
                self.scrapped_jobs.add(self.job["token"])
            self.composer_off()
            self.genre, self.ready, self.next_kept, self.played = None, [], None, set()
            self.wants_play, self.loading = False, None
            self.halt_player()
        return {"event": "genre_result", "ok": True, "id": gid}

    def follow_rename(self, old, new):
        """Point every tune the service holds in folder `old` at `new`."""
        def moved(p):
            return os.path.join(new, os.path.basename(p)) if p and os.path.dirname(p) == old else p
        for t in [self.current, self.next_kept, self.scrap and self.scrap["tune"]] + self.ready:
            if t:
                t["path"] = moved(t["path"])
        self.played = {moved(p) for p in self.played}
        self.meta_pending = {moved(p): h for p, h in self.meta_pending.items()}
        for h in self.meta_pending.values():
            h["path"] = moved(h["path"])
        self.loading = moved(self.loading)
        if self.scrap:
            self.scrap["from"] = moved(self.scrap["from"])
        # mpv keeps the playing file open, but the next one in its playlist
        # is a path, so it is appended again.
        if self.current is not None and self.appended:
            self.appended = None
            self.sync_playlist()

    def check_setup(self):
        if self.dl_cancel:
            self.setup = "downloading"
        elif all(os.path.exists(p) and os.path.getsize(p) == f["bytes"] for f in self.model["files"]
                 for p in [os.path.join(self.models_dir, f["name"])]):
            self.setup = "ready"
        elif self.dl and self.dl.get("error"):
            self.setup = "failed"
        else:
            self.setup = "missing"

    # -- download ------------------------------------------------------------

    def cmd_download(self):
        if self.dl_cancel or self.setup == "ready":
            return
        cancel = threading.Event()
        self.dl_cancel = cancel
        self.dl = {"file": 1, "files": len(self.model["files"]),
                   "name": ROLE_WORDS[self.model["files"][0]["role"]], "done": 0,
                   "total": sum(f["bytes"] for f in self.model["files"]), "rate": 0, "error": None}
        self.check_setup()
        self.changed()

        def progress(i, f, done, total, rate):
            self.results.put((self.download_progress, (True, (cancel, i, f, done, total, rate))))
            try:
                os.write(self.wake_w, b"x")
            except BlockingIOError:
                pass

        def run():
            with self.dl_lock:
                return download(self.model["files"], self.models_dir, self.model["base_url"],
                                self.model["revision"], cancel, progress)
        self.in_thread(run, lambda ok, value: self.download_done(cancel, ok, value))

    def download_progress(self, ok, value):
        cancel, i, f, done, total, rate = value
        if cancel is not self.dl_cancel:
            return
        self.dl.update({"file": i, "name": ROLE_WORDS[f["role"]], "done": done, "total": total,
                        "rate": rate})
        wait = self.dl_last_sent + DOWNLOAD_GAP - time.monotonic()
        if wait <= 0:
            self.dl_last_sent = time.monotonic()
            self.changed()
        elif "download_flush" not in self.timers:
            self.set_timer("download_flush", wait, self.download_flush)

    def download_flush(self):
        self.dl_last_sent = time.monotonic()
        self.changed()

    def download_done(self, cancel, ok, value):
        if cancel is not self.dl_cancel:
            return
        self.dl_cancel = None
        self.cancel_timer("download_flush")
        if not ok:
            text = str(value) if isinstance(value, DownloadError) else f"download failed: {value}"
            self.dl = dict(self.dl, error=text, rate=0)
        else:
            self.dl = None
        self.check_setup()
        self.changed()
        self.maybe_compose()

    def cmd_cancel_download(self):
        if not self.dl_cancel:
            return
        self.dl_cancel.set()
        self.dl_cancel = None
        self.dl = None
        self.cancel_timer("download_flush")
        self.check_setup()
        self.changed()

    # -- genre and player ----------------------------------------------------

    def cmd_genre(self, gid):
        self.read_genres()
        g = next((g for g in self.genres if g["id"] == gid), None)
        if g is None or (self.genre and self.genre["id"] == gid):
            return
        self.wants_play = True
        self.composer_off()
        self.genre = g
        self.ready = []
        self.next_kept = None
        self.played = set()
        self.ensure_mpv()
        cand = self.next_candidate()
        if cand:
            # Shown as playing at once: mpv reports the switch, and the old
            # tune's pause, only some events later, and no snapshot may put
            # the old genre's tune or pause under the new genre.
            self.next_kept = None
            self.current, self.pause, self.loading = cand, False, cand["path"]
            self.pos, self.pos_at = 0.0, time.time()
            self.play_now(cand)
        else:
            self.halt_player()
        self.changed()

    def halt_player(self):
        """Nothing plays from now on; not a stop by the user."""
        if self.current is not None or self.appended:
            self.current, self.appended = None, None
            self.mpv_cmd(["stop"])
            self.changed()

    def cmd_compose(self, on):
        if not on:
            self.composer_off()
            return
        if self.composing or self.genre is None or self.setup != "ready":
            return
        self.composing = True
        self.changed()
        self.maybe_compose()

    def composer_off(self):
        if not self.composing:
            return
        self.composing = False
        self.cancel_job()
        self.stop_server()
        for t in ("retry", "hold_check", "poll"):
            self.cancel_timer(t)
        self.failures, self.retry_at, self.silence_s = 0, None, None
        self.set_state("unloaded")
        self.changed()

    def cmd_play(self, i, name=None):
        q = queue_entries(self.ready, self.next_kept)
        if i >= len(q) or not names_tune(q[i], name):
            return
        if self.ready:
            self.ready.insert(0, self.ready.pop(i))
        self.wants_play = True
        self.play_now(q[i])

    # -- scrap and undo ------------------------------------------------------

    def set_aside(self, tune):
        """Move a tune's file to scrapped/ and arm its deletion; the previous
        scrap is finalised only once the move is done. False when the tune is
        not ours or cannot be moved (said in "error")."""
        if not scrappable(tune["path"], self.music):
            return False
        dest = os.path.join(self.scrapped_dir, os.path.basename(tune["path"]))
        # Two genre folders can hold the same file name.
        if self.scrap and self.scrap["to"] == dest:
            self.finalise_scrap()
        try:
            os.makedirs(self.scrapped_dir, exist_ok=True)
            # A move, not a rename: in the unit ~/Music/Tunes and the cache
            # are separate bind mounts, and rename(2) across them is EXDEV.
            shutil.move(tune["path"], dest)
        except OSError as e:
            self.file_error = f"could not scrap {tune['name']}: {e.strerror}"
            say(self.file_error)
            self.changed()
            return False
        self.file_error = None
        self.finalise_scrap()
        self.scrap = {"tune": tune, "from": tune["path"], "to": dest,
                      "until": time.time() + SCRAP_HOLD * self.scale}
        self.set_timer("scrap", SCRAP_HOLD * self.scale, self.finalise_scrap)
        self.changed()
        return True

    def finalise_scrap(self):
        s = self.scrap
        if s is None:
            return
        self.scrap = None
        self.cancel_timer("scrap")
        for path in (s["to"], self.wave_file(s["from"])):
            try:
                os.unlink(path)
            except FileNotFoundError:
                pass
            except OSError as e:
                say(f"cannot delete a scrapped tune: {e.strerror}")
        self.changed()

    def scrap_playing(self, name=None):
        t = self.current
        if t is None or not names_tune(t, name) or not self.set_aside(t):
            return
        self.current, self.appended = None, None
        cand = self.next_candidate()
        if cand:
            self.play_now(cand)
        else:
            self.mpv_cmd(["stop"])
        self.maybe_compose()

    def scrap_queued(self, i, name=None):
        q = queue_entries(self.ready, self.next_kept)
        if i >= len(q) or not names_tune(q[i], name) or not self.set_aside(q[i]):
            return
        if self.ready:
            self.ready.pop(i)
        else:
            self.next_kept = None
        self.sync_playlist()
        self.maybe_compose()

    def scrap_job(self):
        j = self.job
        if not j:
            return
        if j["stage"] == "finish":
            self.scrapped_jobs.add(j["token"])
        self.cancel_job()
        self.silence_s = None
        self.changed()
        self.maybe_compose()

    def cmd_undo(self):
        s = self.scrap
        if s is None:
            return
        # The undo stays offered until the file is back.
        try:
            shutil.move(s["to"], s["from"])
        except OSError as e:
            self.file_error = f"could not bring {s['tune']['name']} back: {e.strerror}"
            say(self.file_error)
            self.changed()
            return
        self.file_error = None
        self.scrap = None
        self.cancel_timer("scrap")
        self.changed()
        if self.genre and os.path.dirname(s["from"]) == self.genre_dir(self.genre):
            self.ready.insert(0, s["tune"])
            self.sync_playlist()

    def cmd_toggle(self):
        if self.current is not None:
            self.mpv_cmd(["cycle", "pause"])
        elif self.genre:
            self.wants_play = True
            self.start_if_idle()

    def cmd_next(self):
        if self.current is not None and self.appended:
            self.mpv_cmd(["playlist-next"])

    def cmd_seek(self, t):
        if self.current is not None:
            self.mpv_cmd(["seek", t, "absolute"])

    def kept_pool(self):
        busy = {t["path"] for t in self.ready}
        if self.current:
            busy.add(self.current["path"])
        names = self.list_tunes(self.genre)
        paths = [os.path.join(self.genre_dir(self.genre), n) for n in sorted(names)]
        pool = [p for p in paths if p not in busy and p not in self.played]
        if not pool and any(p not in busy for p in paths):
            self.played = {p for p in self.played if p in busy}
            pool = [p for p in paths if p not in busy]
        return pool

    def next_candidate(self):
        if not self.genre:
            return None
        if self.ready:
            return self.ready[0]
        if self.next_kept and os.path.exists(self.next_kept["path"]):
            return self.next_kept
        pool = self.kept_pool()
        if not pool:
            self.next_kept = None
            return None
        self.next_kept = self.kept_tune(self.rng.choice(pool))
        return self.next_kept

    def kept_tune(self, path):
        name = os.path.basename(path)
        parsed = parse_tune_filename(name) or (None, None)
        t = {"name": name[:-4], "bpm": parsed[0], "key": parsed[1], "length": None,
             "kept": True, "wave": [], "path": path}
        cached = self.read_wave(path)
        if cached:
            t.update(cached)
        elif path not in self.meta_pending:
            pending = self.meta_pending[path] = {"path": path}
            self.in_thread(lambda: kept_meta(self.args.ffmpeg, self.args.ffprobe, path),
                           lambda ok, v: self.kept_meta_done(pending, ok, v))
        return t

    def wave_file(self, path):
        genre = os.path.basename(os.path.dirname(path))
        gid = next((g["id"] for g in self.genres if g["name"] == genre), genre)
        return os.path.join(self.wave_dir, gid, os.path.basename(path) + ".json")

    def read_wave(self, path):
        try:
            st = os.stat(path)
            with open(self.wave_file(path)) as f:
                c = json.load(f)
            if c.get("size") == st.st_size and c.get("mtime") == st.st_mtime_ns:
                return {k: c[k] for k in ("name", "length", "wave") if c.get(k) is not None}
        except (OSError, ValueError, AttributeError):
            pass
        return None

    def write_wave(self, path, meta):
        try:
            st = os.stat(path)
            write_atomic(self.wave_file(path), json.dumps(
                dict(meta, size=st.st_size, mtime=st.st_mtime_ns)).encode())
        except OSError as e:
            say(f"cannot write the wave cache: {e.strerror}")

    def kept_meta_done(self, pending, ok, value):
        path = pending["path"]
        self.meta_pending.pop(path, None)
        if not ok:
            say(f"cannot read a kept tune: {value}")
            return
        value = {k: v for k, v in value.items() if v is not None}
        self.write_wave(path, value)
        for t in (self.current, self.next_kept):
            if t and t["path"] == path:
                t.update(value)
                self.changed()

    def play_now(self, tune):
        self.appended = None
        self.mpv_cmd(["loadfile", tune["path"], "replace"])
        self.mpv_cmd(["set_property", "pause", False])

    def start_if_idle(self):
        if self.current is None and self.wants_play:
            cand = self.next_candidate()
            if cand:
                self.play_now(cand)

    def sync_playlist(self):
        """Keep mpv's playlist as the playing tune plus the next candidate."""
        if self.mpv is None:
            return
        if self.current is None:
            self.start_if_idle()
            return
        cand = self.next_candidate()
        path = cand["path"] if cand else None
        if path != self.appended:
            self.mpv_cmd(["playlist-clear"])
            if path:
                self.mpv_cmd(["loadfile", path, "append"])
            self.appended = path

    def on_track(self, path):
        if self.ready and self.ready[0]["path"] == path:
            self.current = self.ready.pop(0)
        elif self.next_kept and self.next_kept["path"] == path:
            self.current = self.next_kept
            self.next_kept = None
        elif not (self.current and self.current["path"] == path):
            self.current = self.kept_tune(path)
        self.loading = None
        self.played.add(path)
        self.appended = None
        self.play_error = None
        self.pos, self.pos_at = 0.0, time.time()
        self.sync_playlist()
        self.changed()
        self.maybe_compose()

    def on_idle(self, natural):
        self.current = None
        self.appended = None
        self.loading = None
        if not natural:
            self.wants_play = False
        self.changed()
        self.start_if_idle()

    # -- mpv -----------------------------------------------------------------

    def ensure_mpv(self):
        if self.mpv is not None:
            return
        path = os.path.join(runtime_dir(), "mpv.sock")
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass
        # Nothing that writes outside the unit's directories: no config, no
        # built-in scripts, no watch-later, no disk cache.
        argv = [self.args.mpv, "--idle=yes", "--no-config", "--load-scripts=no", "--no-ytdl",
                "--save-position-on-quit=no", "--no-resume-playback", "--cache=no",
                "--no-video", "--no-terminal", "--audio-display=no",
                "--audio-client-name=desk-tunes", f"--input-ipc-server={path}"]
        if self.args.mpris:
            argv.append(f"--script={self.args.mpris}")
        if getattr(self.args, "test_ao", None):
            argv.append(f"--ao={self.args.test_ao}")
        # mpv starts fontconfig even with no video, and its cache would go to
        # ~/.cache/fontconfig, which the unit cannot write.
        env = dict(os.environ, XDG_CACHE_HOME=self.mpv_cache)
        child = Child(argv, lambda line: say(f"mpv: {line}"), self.mpv_exited, env=env)
        self.sel.register(child.proc.stderr, selectors.EVENT_READ, ("child", child))
        self.mpv = {"child": child, "path": path, "sock": None, "buf": b"", "out": [], "tries": 0,
                    "req": 0, "wait": {}, "end_reason": None}
        self.set_timer("mpv_connect", 0.05, self.mpv_connect)

    def mpv_connect(self):
        m = self.mpv
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        try:
            s.connect(m["path"])
        except OSError:
            s.close()
            m["tries"] += 1
            if m["tries"] > 200:
                say("mpv's IPC socket never appeared")
                m["child"].signal(signal.SIGKILL)
                return
            self.set_timer("mpv_connect", 0.05, self.mpv_connect)
            return
        m["sock"] = s
        self.sel.register(s, selectors.EVENT_READ, ("mpv", None))
        for i, prop in enumerate(("pause", "idle-active", "path"), 1):
            self.mpv_send({"command": ["observe_property", i, prop]})
        for cmd in m["out"]:
            self.mpv_send(cmd)
        m["out"] = []

    def mpv_send(self, obj):
        try:
            self.mpv["sock"].sendall((json.dumps(obj) + "\n").encode())
        except OSError as e:
            say(f"mpv IPC: {e.strerror}")

    def mpv_cmd(self, command, reply=None):
        if self.mpv is None:
            self.ensure_mpv()
        m = self.mpv
        m["req"] += 1
        obj = {"command": command, "request_id": m["req"]}
        if reply:
            m["wait"][m["req"]] = reply
        if m["sock"] is None:
            m["out"].append(obj)
        else:
            self.mpv_send(obj)

    def mpv_readable(self):
        m = self.mpv
        # mpv's stderr closing in the same select() pass may have dropped it
        # already, and a restarted one may not be connected yet.
        if m is None or m["sock"] is None:
            return
        try:
            data = m["sock"].recv(65536)
        except BlockingIOError:
            return
        except OSError:
            data = b""
        if not data:
            self.sel.unregister(m["sock"])
            m["sock"].close()
            m["sock"] = None
            return
        m["buf"] += data
        while b"\n" in m["buf"]:
            line, m["buf"] = m["buf"].split(b"\n", 1)
            try:
                ev = json.loads(line)
            except ValueError:
                continue
            self.mpv_event(ev)

    def mpv_event(self, ev):
        m = self.mpv
        if "request_id" in ev and ev.get("request_id") in m["wait"]:
            m["wait"].pop(ev["request_id"])(ev)
            return
        kind = ev.get("event")
        if kind == "property-change":
            name, data = ev.get("name"), ev.get("data")
            if name == "pause":
                self.pause = bool(data)
                self.sample_pos()
                self.changed()
            elif name == "path" and isinstance(data, str):
                self.on_track(data)
            elif name == "idle-active" and data is True and self.current is not None:
                self.on_idle(m["end_reason"] == "eof")
        elif kind == "end-file":
            m["end_reason"] = ev.get("reason")
            if ev.get("reason") == "error":
                why = ev.get("file_error") if isinstance(ev.get("file_error"), str) else "unknown error"
                self.play_error = f"mpv could not play the tune: {why}"
                say(self.play_error)
                self.changed()
        elif kind in ("playback-restart", "seek"):
            if kind == "playback-restart":
                self.mpv_exits = 0
            self.sample_pos()

    def sample_pos(self):
        # While a picked tune loads, mpv's position may still be the old one's.
        if self.current is None or self.loading:
            return

        def got(ev):
            if (ev.get("error") == "success" and isinstance(ev.get("data"), (int, float))
                    and not self.loading):
                self.pos, self.pos_at = float(ev["data"]), time.time()
                self.changed()
        self.mpv_cmd(["get_property", "time-pos"], got)

    def mpv_exited(self, child):
        say(f"mpv exited with status {child.proc.returncode}")
        if self.mpv and self.mpv["sock"]:
            self.sel.unregister(self.mpv["sock"])
            self.mpv["sock"].close()
        self.cancel_timer("mpv_connect")
        self.mpv = None
        self.current, self.appended, self.loading = None, None, None
        self.changed()
        if not self.stop_requested and self.genre:
            self.mpv_exits += 1
            self.set_timer("mpv_restart", mpv_restart_delay(self.mpv_exits) * self.scale,
                           self.mpv_restart)

    def mpv_restart(self):
        if self.mpv is None:
            self.ensure_mpv()
            self.start_if_idle()

    # -- model state ---------------------------------------------------------

    def set_state(self, state, detail=None):
        if state != self.state or detail != self.detail:
            self.state, self.detail = state, detail
            self.since = time.time()
            self.changed()

    def cmd_retry(self):
        if self.state in ("failed", "no_device"):
            self.cancel_timer("retry")
            self.retry_at = None
            self.set_state("unloaded")
            self.maybe_compose()

    def can_compose(self):
        return (self.setup == "ready" and self.genre is not None and self.composing
                and self.state not in ("failed", "no_device", "held_game", "held_memory"))

    def maybe_compose(self):
        if not self.can_compose() or self.job:
            return
        if self.new_ready() >= self.cfg["ahead"]:
            self.set_state("idle")
            return
        hold = self.hold_reason(memory=True)
        if hold:
            self.enter_hold(hold)
            return
        if self.server is None:
            self.start_server()
            return
        if not self.server["up"]:
            return
        self.start_job()

    # -- holds ---------------------------------------------------------------

    def hold_reason(self, memory):
        if self.game_running():
            return "held_game"
        if memory:
            try:
                with open(getattr(self.args, "test_meminfo", None) or "/proc/meminfo") as f:
                    free = mem_available(f.read())
            except OSError:
                free = None
            if free is not None and free < self.model["ram_bytes"]:
                return "held_memory"
        return None

    def game_running(self):
        cmd = ["hyprctl"] + ([] if os.environ.get("HYPRLAND_INSTANCE_SIGNATURE") else ["-i", "0"]) + \
            ["-j", "clients"]
        try:
            out = subprocess.run(cmd, capture_output=True, timeout=5)
            clients = json.loads(out.stdout) if out.returncode == 0 else None
        except (OSError, subprocess.TimeoutExpired, ValueError):
            clients = None
        error = None if clients is not None else \
            "hyprctl cannot list the windows, so a game would not hold composing"
        if error != self.hypr_error:
            if error:
                say(error)
            self.hypr_error = error
            self.changed()
        return clients is not None and game_running(clients, self.cfg["game_class_regex"])

    def enter_hold(self, kind):
        self.cancel_job()
        self.stop_server()
        self.silence_s = None
        self.set_state(kind)
        self.set_timer("hold_check", HOLD_WAITING * self.scale, self.hold_tick)

    def hold_tick(self):
        if not self.genre or not self.composing or self.state not in ("held_game", "held_memory"):
            return
        hold = self.hold_reason(memory=True)
        if hold:
            self.set_state(hold)
            self.set_timer("hold_check", HOLD_WAITING * self.scale, self.hold_tick)
        else:
            self.set_state("unloaded")
            self.maybe_compose()

    def running_hold_tick(self):
        if not self.job:
            return
        if self.hold_reason(memory=False):
            self.enter_hold("held_game")
        else:
            self.set_timer("hold_check", HOLD_RUNNING * self.scale, self.running_hold_tick)

    # -- model server --------------------------------------------------------

    def start_server(self):
        # vulkaninfo opens a window for its surface section and crashes in
        # XDestroyWindow when DISPLAY names an X server it cannot reach (the
        # unit's PrivateTmp hides the X socket). The device list it prints
        # does not depend on either variable.
        env = {k: v for k, v in os.environ.items() if k not in ("DISPLAY", "WAYLAND_DISPLAY")}
        try:
            out = subprocess.run([self.args.vulkaninfo, "--summary"], capture_output=True,
                                 timeout=20, env=env)
            text = out.stdout.decode(errors="replace")
        except (OSError, subprocess.TimeoutExpired) as e:
            self.set_state("no_device", f"vulkaninfo failed: {e}")
            return
        index, name = resolve_device(text, self.cfg["device"]["vendor"], self.cfg["device"]["device"])
        if index is None:
            self.set_state("no_device", name)
            return
        probe = socket.socket()
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]
        probe.close()
        argv = [self.args.ace_server, "--models", self.models_dir, "--device", f"Vulkan{index}",
                "--host", "127.0.0.1", "--port", str(port)]
        server = {"port": port, "http": Http(f"http://127.0.0.1:{port}"), "index": index,
                  "name": name, "lines": [], "up": False, "confirmed": False,
                  "base_mem": self.device_mem()}
        server["child"] = Child(argv, lambda line: self.server_line(server, line),
                                lambda child: self.server_exited(server), nice=SERVER_NICE)
        self.sel.register(server["child"].proc.stderr, selectors.EVENT_READ,
                          ("child", server["child"]))
        self.server = server
        self.silence_s = None
        self.set_state("starting")
        self.set_timer("server_start", START_TIMEOUT * self.scale,
                       lambda: self.failure("the model server did not start in time"))

    def server_line(self, server, line):
        server["lines"] = (server["lines"] + [line])[-400:]
        if server is not self.server or server["child"].stopping:
            return
        if line.startswith("[Server] Listening on") and not server["confirmed"]:
            server["confirmed"] = True
            wrong = confirm_device(server["lines"], server["index"], server["name"])
            if wrong:
                self.cancel_timer("server_start")
                self.stop_server()
                self.set_state("no_device", wrong)
                return
            self.set_timer("server_health", 0, self.server_health)

    def server_health(self):
        s = self.server
        if s is None:
            return
        try:
            ok = s["http"].json("GET", "/health").get("status") == "ok"
        except (OSError, ValueError, AttributeError):
            ok = False
        if not ok:
            self.set_timer("server_health", HEALTH_GAP * self.scale, self.server_health)
            return
        self.cancel_timer("server_start")
        s["up"] = True
        self.set_state("idle")
        self.maybe_compose()

    def last_server_message(self, server):
        """The server's last error line, after reading what its stderr holds."""
        if server is None:
            return None
        child = server["child"]
        if child.proc.stderr and not child.proc.stderr.closed:
            child.readable()
        for ln in reversed(server["lines"]):
            if re.search(r"error|fatal|failed|lost|abort", ln, re.I):
                return ln.strip()
        return None

    def server_exited(self, server):
        self.cancel_timer(f"server_kill:{server['port']}")
        if server is not self.server:
            return
        self.server = None
        if server["child"].stopping:
            return
        self.cancel_timer("server_start")
        self.cancel_timer("server_health")
        msg = self.last_server_message(server)
        self.failure(f"the model server exited (status {server['child'].proc.returncode})"
                     + (f": {msg}" if msg else ""))

    def stop_server(self):
        s = self.server
        for t in ("server_start", "server_health"):
            self.cancel_timer(t)
        if s is None or s["child"].stopping:
            return
        s["child"].stopping = True
        s["child"].signal(signal.SIGTERM)
        self.set_timer(f"server_kill:{s['port']}", KILL_GRACE * self.scale,
                       lambda: s["child"].signal(signal.SIGKILL))
        self.server = None

    # -- jobs ----------------------------------------------------------------

    def cancel_job(self):
        j = self.job
        self.job = None
        self.cancel_timer("poll")
        if self.state not in ("held_game", "held_memory"):
            self.cancel_timer("hold_check")
        if j and j.get("id") and self.server and self.server["up"]:
            try:
                self.server["http"].json("POST", f"/job?id={j['id']}&cancel=1")
            except (OSError, ValueError) as e:
                say(f"cancel failed: {e}")
        if self.state in ("writing", "rendering"):
            self.set_state("idle" if self.server and self.server["up"] else "unloaded")

    def start_job(self):
        self.job_seq += 1
        g = self.genre
        self.job = {"token": self.job_seq, "genre": g, "rewrites": 0, "id": None, "stage": None,
                    "bpm": bpm_for(g, self.rng), "caption": caption_for(g, self.rng),
                    "name": name_for(g, self.rng), "cut": None, "write_at": time.time(),
                    "write_mono": time.monotonic()}
        self.set_timer("hold_check", HOLD_RUNNING * self.scale, self.running_hold_tick)
        self.post_lm()

    def post_lm(self):
        j = self.job
        try:
            j["id"] = self.server["http"].json("POST", "/lm", {
                "caption": j["caption"], "lyrics": "[Instrumental]",
                "duration": self.cfg["duration"], "bpm": j["bpm"]})["id"]
        except (OSError, ValueError, KeyError, TypeError) as e:
            self.failure(f"the model server refused the song request: {e}")
            return
        j["stage"] = "lm"
        self.set_state("writing", None)
        self.set_timer("poll", POLL * self.scale, self.poll)

    def poll(self):
        j, s = self.job, self.server
        if not j or not s:
            return
        try:
            status = s["http"].json("GET", f"/job?id={j['id']}")["status"]
        except (OSError, ValueError, KeyError, TypeError) as e:
            try:
                code = s["child"].proc.wait(timeout=2)
            except subprocess.TimeoutExpired:
                self.failure(f"lost the model server: {e}")
                return
            msg = self.last_server_message(s)
            self.failure(f"the model server exited (status {code})" + (f": {msg}" if msg else ""))
            return
        if status == "running":
            self.set_timer("poll", POLL * self.scale, self.poll)
            return
        if status != "done":
            msg = self.last_server_message(s)
            self.failure(f"the {'song' if j['stage'] == 'lm' else 'audio'} job {status}"
                         + (f": {msg}" if msg else ""))
            return
        try:
            body = s["http"].call("GET", f"/job?id={j['id']}&result=1", timeout=60)
        except OSError as e:
            self.failure(f"could not fetch the job's result: {e}")
            return
        if j["stage"] == "lm":
            self.plan_done(body)
        else:
            self.synth_done(body)

    def plan_done(self, body):
        j = self.job
        try:
            plan = json.loads(body)[0]
            verdict = plan_verdict(parse_codes(plan.get("audio_codes")), self.model["silence_code"])
        except (ValueError, IndexError, KeyError, TypeError, AttributeError) as e:
            self.failure(f"the song plan could not be read: {e}")
            return
        if verdict["rewrite"]:
            j["rewrites"] += 1
            if j["rewrites"] >= REWRITES_MAX:
                self.failure(f"{REWRITES_MAX} plans in a row had long silences")
                return
            self.silence_s = round(verdict["rewrite"])
            self.changed()
            self.post_lm()
            return
        self.silence_s = None
        j["cut"] = verdict["cut"]
        j["plan"] = plan
        plan = dict(plan, output_format="wav16")
        try:
            j["id"] = self.server["http"].json("POST", "/synth", plan)["id"]
        except (OSError, ValueError, KeyError, TypeError) as e:
            self.failure(f"the model server refused the audio request: {e}")
            return
        j["stage"] = "synth"
        j["render_at"], j["render_mono"] = time.time(), time.monotonic()
        j["written_s"] = round(j["render_mono"] - j["write_mono"], 1)
        self.set_state("rendering")
        self.set_timer("poll", POLL * self.scale, self.poll)

    def synth_done(self, body):
        j = self.job
        try:
            audio = multipart_audio(body)
        except ValueError as e:
            self.failure(f"the audio result could not be read: {e}")
            return
        j["stage"] = "finish"
        self.cancel_timer("hold_check")
        plan, g = j["plan"], j["genre"]
        bpm = plan.get("bpm") if is_int(plan.get("bpm")) and plan.get("bpm") > 0 else j["bpm"]
        key = plan.get("keyscale") if isinstance(plan.get("keyscale"), str) else ""
        wav = os.path.join(self.work_dir, f"job-{j['token']}.wav")
        # Encoded in the cache and placed in the genre's folder only when
        # done, under the name the genre has then: a rename can come between.
        encoded = os.path.join(self.work_dir, f"job-{j['token']}.mp3")
        try:
            os.makedirs(self.work_dir, exist_ok=True)
            with open(wav, "wb") as f:
                f.write(audio)
        except OSError as e:
            self.failure(f"cannot write the tune: {e.strerror}")
            return
        tags = {"title": j["name"], "genre": g["name"], "TBPM": str(bpm)}
        if key:
            tags["TKEY"] = key
        token = j["token"]

        def work():
            try:
                return finish_tune(self.args.ffmpeg, wav, encoded, j["cut"], tags)
            finally:
                os.unlink(wav)
        self.in_thread(work, lambda ok, v: self.tune_done(token, g, encoded, bpm, key, ok, v))

    def place(self, encoded, genre, bpm, key):
        """Move a finished tune from the cache into the folder its genre has
        now; (its path, the genre as it is now)."""
        g = next((x for x in self.genres if x["id"] == genre["id"]), genre)
        directory = self.genre_dir(g)
        when = datetime.now()
        target = os.path.join(directory, tune_filename(when, bpm, key))
        while os.path.exists(target):
            when = datetime.fromtimestamp(when.timestamp() + 1)
            target = os.path.join(directory, tune_filename(when, bpm, key))
        part = os.path.join(directory, "." + os.path.basename(target) + ".part")
        try:
            os.makedirs(directory, exist_ok=True)
            # A copy, not a rename: in the unit the cache and ~/Music/Tunes
            # are separate bind mounts.
            shutil.copyfile(encoded, part)
            os.replace(part, target)
        except OSError:
            for path in (part, encoded):
                try:
                    os.unlink(path)
                except OSError:
                    pass
            raise
        os.unlink(encoded)
        return target, g

    def tune_done(self, token, genre, encoded, bpm, key, ok, value):
        mine = self.job and self.job["token"] == token
        if token in self.scrapped_jobs:
            self.scrapped_jobs.discard(token)
            if ok:
                try:
                    os.unlink(encoded)
                except OSError as e:
                    say(f"cannot delete a scrapped tune: {e.strerror}")
            return
        if ok:
            try:
                target, genre = self.place(encoded, genre, bpm, key)
            except OSError as e:
                ok, value = False, f"cannot write the tune: {e.strerror}"
        if not ok:
            if mine:
                self.failure(str(value))
            return
        tune = {"name": self.job["name"] if mine else os.path.basename(target)[:-4],
                "bpm": bpm, "key": key or None, "length": value["length"], "kept": False,
                "wave": value["wave"], "path": target}
        self.write_wave(target, {"name": tune["name"], "length": tune["length"],
                                 "wave": tune["wave"]})
        self.prune(genre)
        if not mine:
            return
        j = self.job
        self.timings["writing"] = add_timing(self.timings["writing"], j["written_s"])
        self.timings["rendering"] = add_timing(self.timings["rendering"],
                                               time.monotonic() - j["render_mono"])
        self.save_state()
        self.job = None
        self.failures, self.retry_at = 0, None
        self.ready.append(tune)
        if self.next_kept and self.appended == self.next_kept["path"]:
            self.next_kept = None
        self.set_state("idle" if self.server and self.server["up"] else "unloaded")
        self.sync_playlist()
        self.changed()
        self.maybe_compose()

    def prune(self, genre):
        # A deleted genre's folder is the user's now: delete leaves its tunes.
        if self.genre_by_id(genre["id"]) is None:
            return
        protected = {os.path.basename(t["path"]) for t in self.ready + [self.current, self.next_kept]
                     if t and os.path.dirname(t["path"]) == self.genre_dir(genre)}
        for name in keep_victims(self.list_tunes(genre), self.cfg["keep"], protected):
            path = os.path.join(self.genre_dir(genre), name)
            try:
                os.unlink(path)
                os.unlink(self.wave_file(path))
            except FileNotFoundError:
                pass
            except OSError as e:
                say(f"cannot delete an old tune: {e.strerror}")

    def failure(self, detail):
        self.cancel_job()
        self.stop_server()
        self.cancel_timer("hold_check")
        self.failures += 1
        delay = retry_delay(self.failures) * self.scale
        self.retry_at = time.time() + delay
        self.silence_s = None
        say(f"failure {self.failures}: {detail}")
        self.set_state("failed", detail)
        self.set_timer("retry", delay, self.retry_due)

    def retry_due(self):
        self.retry_at = None
        if self.state == "failed":
            self.set_state("unloaded")
            self.maybe_compose()


