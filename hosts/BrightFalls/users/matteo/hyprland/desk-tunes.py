    # -- loop ----------------------------------------------------------------

    def set_timer(self, name, delay, fn):
        self.timers[name] = (time.monotonic() + delay, fn)

    def cancel_timer(self, name):
        self.timers.pop(name, None)

    def in_thread(self, fn, done):
        def run():
            try:
                result = (True, fn())
            except Exception as e:  # handed back to the loop, which decides
                result = (False, e)
            self.results.put((done, result))
            try:
                os.write(self.wake_w, b"x")
            except BlockingIOError:
                pass
        threading.Thread(target=run, daemon=True).start()

    def changed(self):
        self.dirty = True

    def run(self, listener):
        self.sel.register(listener, selectors.EVENT_READ, ("listen", listener))
        signal.signal(signal.SIGTERM, lambda *_: self.request_stop())
        signal.signal(signal.SIGINT, lambda *_: self.request_stop())
        while not self.stop_requested:
            timeout = None
            if self.timers:
                timeout = max(0.0, min(t for t, _ in self.timers.values()) - time.monotonic())
            for key, _ in self.sel.select(timeout):
                kind, obj = key.data
                if kind == "listen":
                    self.accept(obj)
                elif kind == "client":
                    self.client_readable(obj)
                elif kind == "child":
                    if not obj.readable():
                        self.sel.unregister(obj.proc.stderr)
                        obj.proc.stderr.close()
                        obj.proc.wait()
                        obj.on_exit(obj)
                elif kind == "mpv":
                    self.mpv_readable()
                elif kind == "wake":
                    try:
                        os.read(self.wake_r, 4096)
                    except BlockingIOError:
                        pass
            while not self.results.empty():
                done, result = self.results.get()
                done(*result)
            now = time.monotonic()
            for name, (when, fn) in sorted(self.timers.items(), key=lambda kv: kv[1][0]):
                if when <= now and self.timers.get(name, (None,))[0] == when:
                    del self.timers[name]
                    fn()
            if self.dirty:
                self.dirty = False
                self.broadcast()
        self.shutdown()

    def request_stop(self):
        self.stop_requested = True
        try:
            os.write(self.wake_w, b"x")
        except BlockingIOError:
            pass

    def shutdown(self):
        if self.dl_cancel:
            self.dl_cancel.set()
        server = self.server
        self.cancel_job()
        self.stop_server()
        children = ([server["child"]] if server else []) + ([self.mpv["child"]] if self.mpv else [])
        if self.mpv:
            self.mpv["child"].signal(signal.SIGTERM)
        for child in children:
            try:
                child.proc.wait(timeout=KILL_GRACE)
            except subprocess.TimeoutExpired:
                child.signal(signal.SIGKILL)

    # -- clients -------------------------------------------------------------

    def accept(self, listener):
        conn, _ = listener.accept()
        conn.setblocking(False)
        self.clients[conn] = b""
        self.sel.register(conn, selectors.EVENT_READ, ("client", conn))
        self.send(conn, self.snapshot())

    def drop(self, conn):
        self.clients.pop(conn, None)
        try:
            self.sel.unregister(conn)
        except (KeyError, ValueError):
            pass
        conn.close()

    def send(self, conn, obj):
        data = (json.dumps(obj) + "\n").encode()
        try:
            conn.setblocking(True)
            conn.settimeout(2)
            conn.sendall(data)
            conn.setblocking(False)
        except OSError:
            self.drop(conn)

    def broadcast(self):
        snap = self.snapshot()
        for conn in list(self.clients):
            self.send(conn, snap)

    def client_readable(self, conn):
        try:
            data = conn.recv(65536)
        except BlockingIOError:
            return
        except OSError:
            data = b""
        if not data:
            self.drop(conn)
            return
        buf = self.clients[conn] + data
        while b"\n" in buf:
            line, buf = buf.split(b"\n", 1)
            if line.strip():
                self.command(conn, line)
            if conn not in self.clients:
                return
        if len(buf) > 65536:
            self.send(conn, {"event": "error", "text": "line too long"})
            buf = b""
        self.clients[conn] = buf

    def command(self, conn, line):
        try:
            msg = json.loads(line)
        except ValueError:
            msg = None
        cmd = msg.get("cmd") if isinstance(msg, dict) else None
        handlers = {
            "genre": self.cmd_genre, "toggle": self.cmd_toggle, "next": self.cmd_next,
            "seek": self.cmd_seek, "compose": self.cmd_compose, "scrap": self.scrap_playing,
            "undo": self.cmd_undo, "play": self.cmd_play,
            "retry": self.cmd_retry, "download": self.cmd_download,
            "cancel_download": self.cmd_cancel_download, "refresh": self.changed,
            "genre_get": self.genre_get, "genre_save": self.genre_save,
            "genre_delete": self.genre_delete,
        }
        if TESTING and cmd == "test_timers":
            self.send(conn, {"event": "test_timers", "timers": sorted(self.timers),
                             "threads": threading.active_count()})
            return
        if cmd not in handlers:
            self.send(conn, {"event": "error", "text": "unknown or malformed command"})
            return
        if cmd == "genre" and not isinstance(msg.get("id"), str):
            self.send(conn, {"event": "error", "text": "genre needs an id"})
            return
        if cmd == "seek" and (not isinstance(msg.get("t"), (int, float)) or isinstance(msg["t"], bool)
                              or not math.isfinite(msg["t"]) or msg["t"] < 0):
            self.send(conn, {"event": "error", "text": "seek needs t, seconds"})
            return
        if cmd == "compose" and not isinstance(msg.get("on"), bool):
            self.send(conn, {"event": "error", "text": "compose needs on, true or false"})
            return
        index = msg.get("i")
        if ((cmd == "play" or (cmd == "scrap" and "i" in msg))
                and (not is_int(index) or index < 0)):
            self.send(conn, {"event": "error", "text": f"{cmd} needs i, a queue index"})
            return
        if cmd == "scrap" and "job" in msg and msg["job"] is not True:
            self.send(conn, {"event": "error", "text": "scrap's job can only be true"})
            return
        name = msg.get("name")
        if cmd in ("play", "scrap") and "name" in msg and not isinstance(name, str):
            self.send(conn, {"event": "error", "text": f"{cmd}'s name is the tune's name"})
            return
        if cmd in ("genre_get", "genre_delete") and not isinstance(msg.get("id"), str):
            self.send(conn, {"event": "error", "text": f"{cmd} needs an id"})
            return
        if cmd == "genre_save":
            try:
                if "id" not in msg or not (msg["id"] is None or isinstance(msg["id"], str)):
                    raise TypeError("genre_save needs id, a genre's id or null")
                fields = edit_fields(msg.get("genre"))
                if msg.get("base") is not None and not isinstance(msg["base"], dict):
                    raise TypeError("genre_save's base is the fields genre_get gave")
            except TypeError as e:
                self.send(conn, {"event": "error", "text": str(e)})
                return
            self.send(conn, self.genre_save(msg["id"], fields, msg.get("base")))
            self.changed()
        elif cmd in ("genre_get", "genre_delete"):
            self.send(conn, handlers[cmd](msg["id"]))
            self.changed()
        elif cmd == "genre":
            self.cmd_genre(msg["id"])
        elif cmd == "seek":
            self.cmd_seek(float(msg["t"]))
        elif cmd == "compose":
            self.cmd_compose(msg["on"])
        elif cmd == "play":
            self.cmd_play(index, name)
        elif cmd == "scrap":
            if msg.get("job") is True:
                self.scrap_job()
            elif "i" in msg:
                self.scrap_queued(index, name)
            else:
                self.scrap_playing(name)
        else:
            handlers[cmd]()

