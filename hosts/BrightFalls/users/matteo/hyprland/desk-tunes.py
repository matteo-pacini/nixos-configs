def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def validate_config(raw):
    """The config as read, or ValueError naming the first key at fault."""
    def need(cond, key):
        if not cond:
            raise ValueError(key)
    need(isinstance(raw, dict), "(file)")
    m = raw.get("model")
    need(isinstance(m, dict), "model")
    for k in ("name", "variant", "revision", "base_url"):
        need(isinstance(m.get(k), str) and m[k], f"model.{k}")
    files = m.get("files")
    need(isinstance(files, list) and files, "model.files")
    roles = set()
    for i, f in enumerate(files):
        need(isinstance(f, dict), f"model.files[{i}]")
        need(f.get("role") in ROLE_WORDS, f"model.files[{i}].role")
        need(isinstance(f.get("name"), str) and re.fullmatch(r"[A-Za-z0-9._-]+", f["name"])
             and not f["name"].startswith("."), f"model.files[{i}].name")
        need(isinstance(f.get("sha256"), str) and re.fullmatch(r"[0-9a-f]{64}", f["sha256"]),
             f"model.files[{i}].sha256")
        need(is_int(f.get("bytes")) and f["bytes"] > 0, f"model.files[{i}].bytes")
        roles.add(f["role"])
    need(roles == set(ROLE_WORDS), "model.files")
    need(is_int(m.get("silence_code")) and m["silence_code"] >= 0, "model.silence_code")
    need(is_int(m.get("ram_bytes")) and m["ram_bytes"] > 0, "model.ram_bytes")
    d = raw.get("device")
    need(isinstance(d, dict), "device")
    for k in ("vendor", "device"):
        need(isinstance(d.get(k), str) and re.fullmatch(r"0x[0-9a-fA-F]{1,8}", d[k]), f"device.{k}")
    need(isinstance(d.get("label"), str) and d["label"], "device.label")
    need(isinstance(raw.get("game_class_regex"), str), "game_class_regex")
    try:
        re.compile(raw["game_class_regex"])
    except re.error:
        raise ValueError("game_class_regex")
    for k in ("keep", "ahead", "duration"):
        need(is_int(raw.get(k)) and raw[k] > 0, k)
    return raw


def parse_genres(text):
    """The genres list from the file's text, or ValueError with the reason."""
    try:
        raw = json.loads(text)
    except ValueError:
        raise ValueError("not valid JSON")
    if not isinstance(raw, dict) or not isinstance(raw.get("genres"), list) or not raw["genres"]:
        raise ValueError('needs a non-empty "genres" list')
    out, ids, names = [], set(), set()
    for i, g in enumerate(raw["genres"]):
        where = f"genre {i + 1}"
        if not isinstance(g, dict):
            raise ValueError(f"{where} is not an object")
        if not isinstance(g.get("id"), str) or not GENRE_ID.match(g["id"]) or g["id"] in ids:
            raise ValueError(f"{where}: id missing, repeated or not lower-case letters, digits and dashes")
        name = g.get("name")
        if (not isinstance(name, str) or not name.strip() or "/" in name or name.startswith(".")
                or name in names or any(ord(c) < 32 or ord(c) == 127 for c in name)):
            raise ValueError(f"{where}: name missing, repeated, or usable as no folder name")
        if not isinstance(g.get("caption"), str) or not g["caption"].strip():
            raise ValueError(f"{where}: caption missing")
        for key in ("turns", "moods", "things"):
            v = g.get(key, DEFAULT_WORDS.get(key))
            if (not isinstance(v, list) or (key != "turns" and not v)
                    or not all(isinstance(s, str) and s.strip() for s in v)):
                raise ValueError(f"{where}: {key} must be a list of texts"
                                 + ("" if key == "turns" else ", not empty"))
        b = g.get("bpm")
        if (not isinstance(b, list) or len(b) != 2 or not all(is_int(x) for x in b)
                or not BPM_MIN <= b[0] <= b[1] <= BPM_MAX):
            raise ValueError(f"{where}: bpm must be [low, high] between {BPM_MIN} and {BPM_MAX}")
        ids.add(g["id"])
        names.add(name)
        out.append(dict({k: g[k] for k in ("id", "name", "caption", "turns", "bpm")},
                        **{k: g.get(k, DEFAULT_WORDS[k]) for k in DEFAULT_WORDS}))
    return out


def edit_fields(raw):
    """The editor's fields from a genre_save's "genre": name and caption
    trimmed, turns trimmed with blank and repeated lines dropped, bpm as
    sent. TypeError when a field has the wrong shape."""
    if not isinstance(raw, dict):
        raise TypeError("genre_save needs a genre object")
    for k in ("name", "caption"):
        if not isinstance(raw.get(k), str):
            raise TypeError(f"genre_save needs {k}, a text")
    turns = raw.get("turns")
    if not isinstance(turns, list) or not all(isinstance(s, str) for s in turns):
        raise TypeError("genre_save needs turns, a list of texts")
    bpm = raw.get("bpm")
    if (not isinstance(bpm, list) or len(bpm) != 2
            or not all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in bpm)):
        raise TypeError("genre_save needs bpm, two numbers")
    lines = []
    for s in turns:
        s = s.strip()
        if s and s not in lines:
            lines.append(s)
    return {"name": raw["name"].strip(), "caption": raw["caption"].strip(), "turns": lines,
            "bpm": list(bpm)}


def field_error(fields, genres, self_id):
    """(field, text for the user) for the first rule `fields` (from
    edit_fields) breaks, or None. Names are unique among `genres` ignoring
    case, not counting the genre `self_id`."""
    # The panel (tunes.js check()) applies these rules in this order with
    # these texts; keep the two the same.
    name = fields["name"]
    if not name:
        return "name", "A genre needs a name."
    if any(unicodedata.category(c) == "Cc" for c in name):
        return "name", "A name cannot hold control characters or line breaks."
    if "/" in name:
        return "name", "A name cannot contain a slash: it is also a folder's name."
    if name.startswith("."):
        return "name", "A name cannot start with a dot."
    if len(name) > NAME_MAX:
        return "name", f"A name is at most {NAME_MAX} characters; this one has {len(name)}."
    other = next((g for g in genres if g["id"] != self_id
                  and g["name"].lower() == name.lower()), None)
    if other:
        return "name", f"There is already a genre called {other['name']}."
    if not fields["caption"]:
        return "caption", "A genre needs a prompt."
    if len(fields["caption"]) > CAPTION_MAX:
        return "caption", (f"A prompt is at most {CAPTION_MAX} characters; "
                           f"this one has {len(fields['caption'])}.")
    for i, s in enumerate(fields["turns"], 1):
        if len(s) > TURN_MAX:
            return "turns", f"Line {i} is longer than {TURN_MAX} characters."
    if len(fields["turns"]) > TURNS_MAX:
        return "turns", f"At most {TURNS_MAX} variations; this has {len(fields['turns'])}."
    lo, hi = fields["bpm"]
    if not is_int(lo):
        return "bpm", "The slowest tempo needs a whole number."
    if not is_int(hi):
        return "bpm", "The fastest tempo needs a whole number."
    if not (BPM_MIN <= lo <= BPM_MAX and BPM_MIN <= hi <= BPM_MAX):
        return "bpm", f"Tempos go from {BPM_MIN} to {BPM_MAX} BPM."
    if lo > hi:
        return "bpm", "The slowest tempo is above the fastest."
    return None


def new_genre_id(name, taken):
    """A genre id for `name`, not among `taken`: lower-case letters, digits
    and dashes, accents dropped."""
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    base = re.sub(r"[^a-z0-9]+", "-", ascii_name.lower()).strip("-") or "genre"
    gid, n = base, 2
    while gid in taken:
        gid, n = f"{base}-{n}", n + 1
    return gid


def format_genres(doc):
    """The genres file's text for `doc`, laid out as the repository's file:
    two-space indents, a genre's "turns" one per line, every other value on
    its key's line. Keys keep their order; unknown ones are kept."""
    def value(key, v):
        if key == "turns" and isinstance(v, list) and v:
            return "[\n" + ",\n".join("        " + dumps(s) for s in v) + "\n      ]"
        return dumps(v)

    def genre(g):
        return "    {\n" + ",\n".join(f"      {dumps(k)}: {value(k, v)}" for k, v in g.items()) + "\n    }"

    def top(k, v):
        if k == "genres":
            return '  "genres": [\n' + ",\n".join(genre(g) for g in v) + "\n  ]"
        return f"  {dumps(k)}: {dumps(v)}"
    return "{\n" + ",\n".join(top(k, v) for k, v in doc.items()) + "\n}\n"


