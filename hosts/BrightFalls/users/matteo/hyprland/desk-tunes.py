"""Endless generated instrumental music for the Quickshell tunes panel.

`desk-tunes serve` is the service (a systemd user unit). Playing and
composing are separate: the player (mpv, audio only, driven over its JSON
IPC, client name "desk-tunes", with mpv's MPRIS plugin so media keys and
playerctl reach it) plays the selected genre's kept tunes and what the
composer finishes; the composer is a switch, and only while it is on does
the model server run (acestep.cpp's ace-server, a niced child bound to
127.0.0.1 on a port it picks, killed when the switch goes off, on a hold or
a failure). The service also owns the queue, the files and the weights
download. Idle (nothing playing, composer off, no scrap waiting) it blocks
on its sockets with no timer armed.

`desk-tunes attach` is the shell's thin client: stdin lines go to the
service's socket, the socket's lines to stdout. Exit 0 when stdin closes,
1 when the socket closes or refuses, 3 (with one stderr line) when the
socket file does not exist.

Usage: desk-tunes serve [--config FILE] [--genres FILE] [--ace-server EXE]
                        [--mpv EXE] [--mpris SO] [--ffmpeg EXE]
                        [--ffprobe EXE] [--vulkaninfo EXE]
       desk-tunes attach

Defaults are the paths the package was built with; --genres defaults to
$XDG_CONFIG_HOME/desk/tunes/genres.json. hyprctl is the one on PATH (with
`-i 0` when HYPRLAND_INSTANCE_SIGNATURE is unset).

Files:
  socket   $XDG_RUNTIME_DIR/desk-tunes/sock (directory 0700); mpv's IPC
           socket beside it
  weights  $XDG_DATA_HOME/desk-tunes/models/<name> (<name>.part while
           downloading)
  tunes    ~/Music/Tunes/<genre name>/<YYYYMMDD-HHMMSS>-<bpm>bpm-<key>.mp3,
           key with its spaces as dashes ("C#-minor"); the newest `keep` per
           genre are kept, and only files matching that pattern are ever
           deleted, never the playing or queued ones
  waves    $XDG_CACHE_HOME/desk-tunes/wave/<genre id>/<tune file>.json
  scrapped $XDG_CACHE_HOME/desk-tunes/scrapped/<tune file>: a scrapped tune
           while it can be undone; emptied at start
  mpv      $XDG_CACHE_HOME/desk-tunes/mpv: mpv's XDG_CACHE_HOME, where its
           fontconfig writes the font cache
  state    $XDG_STATE_HOME/desk-tunes/state.json: {"writing":[s, ...],
           "rendering":[s, ...]}, how long each stage took for the last 5
           finished tunes, written atomically and only on change

Config (--config, generated by Nix):
  {"model":{"name","variant","revision","base_url",
            "files":[{"role":"lm"|"dit"|"text"|"vae","name","sha256","bytes"}],
            "silence_code":35847,"ram_bytes":6442450944},
   "device":{"vendor":"0x1002","device":"0x1900","label":"Radeon 780M"},
   "game_class_regex":"...","keep":50,"ahead":2,"duration":180}
  A file's URL is <base_url>/resolve/<revision>/<name>.

Genres (--genres, edited by hand and from the panel, read again whenever
it changes): {"genres":[{"id","name","caption","turns":[str, ...],
"bpm":[lo,hi],"moods":[str, ...],"things":[str, ...]}]}. A genre without
moods or things takes them from a word list built in here. A broken file
keeps the last good list and sets "error". The service writes it only for
genre_save and genre_delete: it reads the file again first (keeping any
edit made by hand since, unknown keys and a genre's moods and things),
refuses while it is broken, and replaces it through
.<file name>.new beside it (deleted at start if a crash left it), laid out
as the repository's copy (two-space indents, a genre's turns one per line,
every other value on its key's line) and only when the text changes.

Protocol: JSON lines, one object per line, UTF-8.

Service -> client. On attach and after every change one full snapshot
(changes in one loop pass are coalesced; download progress at most twice a
second; nothing periodic otherwise):
  {"event":"state","v":1,
   "setup":"missing"|"downloading"|"ready"|"failed",
   "download":null|{"file":2,"files":4,"name":"language model","done":B,
                    "total":B,"rate":Bps,"error":null|"text"},
       done/total over all files; kept after a failure with its error,
       null after a cancel or once every file is in place.
   "need":{"download_bytes":B,"disk_free_bytes":B,"ram_bytes":B},
   "genres":[{"id","name","kept":31}, ...],      order of the genres file
   "genre":null|"lofi",                          null until one is picked
   "kept_total":31,           kept tunes of the selected genre on disk
   "composing":false,         the switch
   "ahead":2,                 finished tunes the composer keeps queued
   "player":"none"|"playing"|"paused",
   "stopped":false,           the user stopped the player (Stop, or mpv
                              failed to play), so nothing starts by itself
                              until toggle, play or a genre pick
   "tune":null|{"name","file","bpm","key","length","kept":false,
                "wave":[78 numbers 0..1]},
       name is the file name, bpm, key and length null, until a kept
       tune's file has been read; file is always the file name (without
       ".mp3")
   "pos":84.0,"pos_at":1795390000.25,  the panel interpolates while playing
   "queue":[{"name","file","bpm","key","length","kept"}, ...],
       what "next" would play, in order: the queued tunes, or with none
       queued the next kept tune (one entry); index i in scrap and play
   "ready":2,                 new tunes in the queue
   "kept_playing":false,      a kept tune plays because no new tune is
                              queued
   "can_next":false,          "next" would play another tune
   "job":null|{"stage":"writing"|"rendering","started":unix,
               "expect_s":null|s,"written_s":null|s},
       started: when this stage began; expect_s: the stage's median;
       written_s: how long this tune's writing took, set while rendering
   "expect":null|{"writing_s","rendering_s"},  the medians, null until
                              one tune has been timed
   "undo":null|{"name","until":unix,"genre":null|"lofi"},  the scrapped
                              tune that "undo" brings back until then, and
                              the genre whose folder it goes back to
   "model":{"name","variant","device",
            "state":"unloaded"|"starting"|"idle"|"writing"|"rendering"|
                    "held_game"|"held_memory"|"failed"|"no_device",
            "since":unix,"silence_s":null|39,"detail":null|"text",
            "failures":0,"retry_at":null|unix,
            "ram_used_bytes":null|B,"ram_free_bytes":B},
       state is "unloaded" while the switch is off and "idle" while it
       rests because the queue is full; ram_used_bytes = the server's RSS
       plus what the device's VRAM and GTT grew by since the server
       started; null with no server.
   "error":null|"text"}       the first of: the genres file is broken, mpv
                              could not play the last tune (until one plays),
                              the last scrap or undo could not move its file
                              (until one can), hyprctl cannot list the
                              windows (until it can)
  {"event":"error","text":"..."}  to the sender of a malformed line only.
  {"event":"genre","id","name","caption","turns","bpm"} and
  {"event":"genre_result","ok":true,"id","renamed":null|{"from","to"}}
  (genre_delete: no "renamed") or
  {"event":"genre_result","ok":false,"field":"name"|"caption"|"turns"|
  "bpm"|null,"text":"a sentence for the user"}: the answers to the genre
  commands, to their sender only, before the snapshot they cause.

Client -> service: {"cmd":"genre","id":"lofi"} | {"cmd":"toggle"} |
{"cmd":"next"} | {"cmd":"seek","t":61.0} | {"cmd":"compose","on":true|false}
| {"cmd":"scrap"} | {"cmd":"scrap","i":N} | {"cmd":"scrap","job":true} |
{"cmd":"undo"} | {"cmd":"play","i":N} | {"cmd":"retry"} | {"cmd":"download"}
| {"cmd":"cancel_download"} | {"cmd":"refresh"} |
{"cmd":"genre_get","id":"jazz"} | {"cmd":"genre_save","id":"jazz"|null,
"genre":{"name","caption","turns":[str, ...],"bpm":[lo,hi]},
"base":{"name","caption","turns","bpm"}} ("base" optional) |
{"cmd":"genre_delete","id":"jazz"}. A command that does not apply is
ignored. scrap (but for the job) and play take an optional
"name": the name the sender saw for that tune, or its file; a command whose
name is not the tune's at that place now (the queue moved, or another tune
started, since the sender's snapshot) is ignored.

Behaviour:
  genre     picks the genre and plays what is kept for it (the genre
            already picked: ignored): a kept tune (shuffled, none twice
            until all have played) starts at once; with none kept nothing
            plays. It starts clean: not paused, not "stopped", the old
            genre's tune out of the player. It turns the composer off and
            drops the old genre's queued tunes (their files stay).
  compose   on (with the weights in place and a genre picked): one job at
            a time while fewer than `ahead` new tunes are queued, so a
            paused player gets the queue filled and no more; the model
            state is "idle" while the queue is full. The first finished
            tune starts by itself when nothing plays, unless "stopped".
            Off: cancels the job and stops the server.
  queue     with no new tune queued, the next is a kept one.
  toggle    pauses or resumes the playing tune; with none playing (after
            a stop or an error) starts the next one, or the first new one
            when it is ready.
  next      goes to the tune after the playing one, new or kept: ignored
            when there is none. The same as MPRIS Next, which mpv's playlist carries.
  play i    plays queue entry i now; the rest of the queue keeps its order.
  scrap     the playing tune (the next starts at once, or nothing plays),
            queue entry i, or the job (cancelled, and another starts; no
            undo). A scrapped tune leaves the player or queue at once; its
            file moves to scrapped/ and is deleted with its wave cache 10 s
            later, or at once by the next scrap once that one's file has
            moved. Only files named as ours, in a genre folder, are
            scrapped. A move that fails is said in "error" and leaves the
            tune where it was and the previous undo offered.
  undo      within those 10 s: the file goes back and the tune to the head
            of the queue (its genre still picked), without interrupting
            what plays. A move back that fails is said in "error" and
            leaves the undo offered.
  timing    how long writing (from the first plan asked for to the plan
            kept) and rendering (to the finished file) took is recorded for
            each finished tune; the medians of the last 5 are reported.
  a tune    POST /lm {caption, "[Instrumental]", duration, bpm}, polled
            every 0.5 s; the plan's codes (5 a second) are read for the
            silence code: a final run of at least 1 s is cut with a 1.5 s
            fade, any other run over 5 s throws the plan away and the LM
            writes again (silence_s set); a third such plan for one tune is
            a failure. Then POST /synth with the plan, WAV out, ffmpeg trims,
            fades and encodes the MP3 (title, genre, TBPM, TKEY). The
            decoded loudness is checked: a run over 5 s under -50 dB that is
            not the tail discards the tune as a failure.
  failure   the job is cancelled and the server stopped; retried after 3 s
            the first time, then every 30 s ("retry" tries now). The count
            resets with the next finished tune. The player is unaffected.
  holds     only while the composer is on: checked before each job (game
            and memory), every 10 s while one runs (game) and every 30 s
            while held (both): a client of `hyprctl -j clients`
            whose class matches game_class_regex in full (as Hyprland
            matches a rule), or MemAvailable under
            ram_bytes. A hold cancels the job and stops the server; it
            lifts by itself and leaves the switch on.
  device    at every server start the Vulkan index is resolved from
            `vulkaninfo --summary` (run without DISPLAY and
            WAYLAND_DISPLAY; its exit status ignored) by PCI vendor and device id, counting
            GPUs as ggml does (discrete and integrated only, one per device
            UUID), passed as --device Vulkan<N>, and confirmed from the
            server's own "ggml_vulkan: N = <name>" line. Not found or not
            confirmed: state no_device with what was found; no fallback,
            "retry" tries again.
  download  one file at a time into <name>.part, resumed with Range,
            sha256 checked, then renamed; runs with no client attached;
            cancel keeps finished files and the partial one. A download
            asked for right after a cancel waits for the cancelled one to
            stop writing.
  mpv       restarted after it exits, 2 s later, doubling to 60 s while it
            keeps exiting before a tune plays.
  start     a `.<tune file>.part` left in a genre folder by a tune that was
            never placed is deleted.
  placing   a tune is encoded in the cache and placed in its genre's folder
            as the genre is named when the encode ends.
  genre_get a genre's editable fields; an unknown id is refused.
  genre_save
            id null adds a genre at the end, with an id made from its name;
            a folder of that name already in ~/Music/Tunes is its kept
            tunes. Fields are trimmed, blank and repeated turns dropped,
            then checked (field_error): name 1-40 characters, no "/", no
            leading ".", no control characters, unique ignoring case;
            caption 1-400; 0-20 turns of 1-120; bpm two integers,
            30 <= lo <= hi <= 300. With "base" (the fields genre_get gave),
            refused when the genre in the file differs from it, so an edit
            by hand meanwhile is not lost. A new name renames the genre's folder
            (refused when a folder of that name exists); the id never
            changes, so its wave cache stays, and the tunes playing and
            queued play on from the new folder. The selected genre's new
            values apply from the next tune started.
  genre_delete
            refused for the last genre. The folder and its tunes stay. For
            the selected genre: its tune leaves the player, the composer
            goes off and no genre is selected.
"""

