class DownloadError(Exception):
    pass


def download(files, directory, base_url, revision, cancel, progress):
    """Fetch every missing file; progress(i, name, done, total, rate)."""
    total = sum(f["bytes"] for f in files)
    done = 0
    window = []
    os.makedirs(directory, exist_ok=True)
    for i, f in enumerate(files, 1):
        final = os.path.join(directory, f["name"])
        part = final + ".part"
        if os.path.exists(final) and os.path.getsize(final) == f["bytes"]:
            done += f["bytes"]
            continue
        digest = hashlib.sha256()
        offset = os.path.getsize(part) if os.path.exists(part) else 0
        if offset > f["bytes"]:
            os.unlink(part)
            offset = 0
        if offset:
            with open(part, "rb") as p:
                for block in iter(lambda: p.read(1 << 20), b""):
                    digest.update(block)
        req = urllib.request.Request(f"{base_url}/resolve/{revision}/{f['name']}",
                                     headers={"User-Agent": "desk-tunes"})
        if offset:
            req.add_header("Range", f"bytes={offset}-")
        try:
            resp = urllib.request.urlopen(req, timeout=30)
        except urllib.error.HTTPError as e:
            raise DownloadError(f"{f['name']}: HTTP {e.code}")
        except (urllib.error.URLError, OSError) as e:
            raise DownloadError(f"{f['name']}: {getattr(e, 'reason', e)}")
        with resp:
            if offset and resp.status != 206:
                offset = 0
                digest = hashlib.sha256()
            mode = "ab" if offset else "wb"
            got = offset
            progress(i, f, done + got, total, 0)
            with open(part, mode) as out:
                while True:
                    if cancel.is_set():
                        return False
                    try:
                        block = resp.read1(1 << 20)
                    except (OSError, http.client.HTTPException) as e:
                        raise DownloadError(f"{f['name']}: the connection broke ({type(e).__name__})")
                    if not block:
                        break
                    out.write(block)
                    digest.update(block)
                    got += len(block)
                    now = time.monotonic()
                    window.append((now, len(block)))
                    while window and window[0][0] < now - 2:
                        window.pop(0)
                    span = max(now - window[0][0], 0.5)
                    progress(i, f, done + got, total, int(sum(b for _, b in window) / span))
        if got != f["bytes"]:
            raise DownloadError(f"{f['name']}: got {got} of {f['bytes']} bytes")
        if digest.hexdigest() != f["sha256"]:
            os.unlink(part)
            raise DownloadError(f"{f['name']}: checksum mismatch")
        os.replace(part, final)
        done += f["bytes"]
    return True


def decode_mono(ffmpeg, path):
    out = subprocess.run([ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-i", path,
                          "-ac", "1", "-ar", str(DECODE_RATE), "-f", "s16le", "-"],
                         capture_output=True, timeout=120)
    if out.returncode != 0:
        raise RuntimeError("ffmpeg could not decode " + os.path.basename(path))
    samples = array("h")
    samples.frombytes(out.stdout[:len(out.stdout) // 2 * 2])
    if sys.byteorder != "little":
        samples.byteswap()
    return samples


def finish_tune(ffmpeg, wav, target, cut, tags):
    """Encode `wav` to `target` (cut and faded when cut is set), then check
    it. Returns {"length","wave"} or raises RuntimeError."""
    part = os.path.join(os.path.dirname(target), "." + os.path.basename(target) + ".part")
    cmd = [ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-i", wav]
    if cut is not None:
        cmd += ["-t", f"{cut:.3f}", "-af", f"afade=t=out:st={max(0.0, cut - FADE):.3f}:d={FADE}"]
    cmd += ["-c:a", "libmp3lame", "-b:a", "128k", "-id3v2_version", "3"]
    for k, v in tags.items():
        cmd += ["-metadata", f"{k}={v}"]
    cmd += ["-f", "mp3", part]
    out = subprocess.run(cmd, capture_output=True, timeout=300)
    if out.returncode != 0:
        try:
            os.unlink(part)
        except FileNotFoundError:
            pass
        raise RuntimeError("ffmpeg could not encode the tune: "
                           + out.stderr.decode(errors="replace").strip()[-200:])
    try:
        samples = decode_mono(ffmpeg, part)
        quiet = quiet_mid_run(levels_db(samples))
        if quiet > QUIET_MAX:
            raise RuntimeError(f"the rendered tune is silent for {quiet:.0f} s in the middle")
    except BaseException:
        os.unlink(part)
        raise
    os.replace(part, target)
    return {"length": round(len(samples) / DECODE_RATE, 1), "wave": wave_bars(samples)}


def kept_meta(ffmpeg, ffprobe, path):
    samples = decode_mono(ffmpeg, path)
    title = None
    out = subprocess.run([ffprobe, "-v", "error", "-show_entries", "format_tags=title",
                          "-of", "json", path], capture_output=True, timeout=30)
    if out.returncode == 0:
        try:
            title = json.loads(out.stdout)["format"]["tags"]["title"]
        except (ValueError, KeyError, TypeError):
            pass
    return {"name": title, "length": round(len(samples) / DECODE_RATE, 1),
            "wave": wave_bars(samples)}


class Http:
    def __init__(self, base):
        self.base = base

    def call(self, method, path, body=None, timeout=10):
        data = None if body is None else json.dumps(body).encode()
        req = urllib.request.Request(self.base + path, data=data, method=method)
        if data is not None:
            req.add_header("Content-Type", "application/json")
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.read()

    def json(self, method, path, body=None):
        return json.loads(self.call(method, path, body))


class Child:
    """A child process whose stderr the loop reads line by line."""

    def __init__(self, argv, on_line, on_exit, nice=0, env=None):
        def pre():
            if nice:
                os.nice(nice)
        self.proc = subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                     stderr=subprocess.PIPE, start_new_session=True,
                                     preexec_fn=pre, env=env)
        self.on_line, self.on_exit = on_line, on_exit
        self.buf = b""
        self.stopping = False
        os.set_blocking(self.proc.stderr.fileno(), False)

    def readable(self):
        try:
            data = os.read(self.proc.stderr.fileno(), 65536)
        except BlockingIOError:
            return True
        if not data:
            return False
        self.buf += data
        while b"\n" in self.buf:
            line, self.buf = self.buf.split(b"\n", 1)
            self.on_line(line.decode(errors="replace"))
        return True

    def signal(self, sig):
        try:
            os.killpg(self.proc.pid, sig)
        except ProcessLookupError:
            pass


