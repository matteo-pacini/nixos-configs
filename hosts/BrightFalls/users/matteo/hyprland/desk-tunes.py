"""Endless generated instrumental music for the Quickshell tunes panel.

`desk-tunes serve` is the service (a systemd user unit). It owns the model
server (acestep.cpp's ace-server, a niced child bound to 127.0.0.1 on a port
it picks, started on load and killed on unload, hold or failure), the player
(mpv, audio only, driven over its JSON IPC, client name "desk-tunes", with
mpv's MPRIS plugin so media keys and playerctl reach it), the queue, the
files and the weights download. Idle (nothing playing, model unloaded) it
blocks on its sockets with no timer armed.

`desk-tunes attach` is the shell's thin client: stdin lines go to the
service's socket, the socket's lines to stdout. Exit 0 when stdin closes,
1 when the socket closes or refuses, 3 (with one stderr line) when the
socket file does not exist.

Usage: desk-tunes serve [--config FILE] [--genres FILE] [--ace-server EXE]
                        [--mpv EXE] [--mpris SO] [--ffmpeg EXE]
                        [--ffprobe EXE] [--vulkaninfo EXE]
       desk-tunes attach

Defaults are the paths the package was built with; --genres defaults to
$XDG_CONFIG_HOME/desk/tunes-genres.json. hyprctl is the one on PATH (with
`-i 0` when HYPRLAND_INSTANCE_SIGNATURE is unset).

Files:
  socket   $XDG_RUNTIME_DIR/desk-tunes/sock (directory 0700); mpv's IPC
           socket beside it
  weights  $XDG_DATA_HOME/desk-tunes/models/<name> (<name>.part while
           downloading)
  tunes    ~/Music/Tunes/<genre name>/<YYYYMMDD-HHMMSS>-<bpm>bpm-<key>.mp3,
           key with its spaces as dashes ("C#-minor"); the newest `keep` per
           genre are kept, and only files matching that pattern are ever
           deleted, never the playing or queued ones
  waves    $XDG_CACHE_HOME/desk-tunes/wave/<genre id>/<tune file>.json
  mpv      $XDG_CACHE_HOME/desk-tunes/mpv: mpv's XDG_CACHE_HOME, where its
           fontconfig writes the font cache
  state    $XDG_STATE_HOME/desk-tunes/state.json: {"counter"}, the last
           tune's number, written atomically and only on change

Config (--config, generated by Nix):
  {"model":{"name","variant","revision","base_url",
            "files":[{"role":"lm"|"dit"|"text"|"vae","name","sha256","bytes"}],
            "silence_code":35847,"ram_bytes":6442450944},
   "device":{"vendor":"0x1002","device":"0x1900","label":"Radeon 780M"},
   "game_class_regex":"...","keep":50,"ahead":2,"duration":180}
  A file's URL is <base_url>/resolve/<revision>/<name>.

Genres (--genres, hand-edited, read again whenever its size or mtime
changes): {"genres":[{"id","name","caption","turns":[>=6 str],
"bpm":[lo,hi],"moods":[>=8 str],"things":[>=8 str]}]}. A broken file keeps
the last good list and sets "error".

Protocol: JSON lines, one object per line, UTF-8.

Service -> client. On attach and after every change one full snapshot
(changes in one loop pass are coalesced; download progress at most twice a
second; nothing periodic otherwise):
  {"event":"state","v":1,
   "setup":"missing"|"downloading"|"ready"|"failed",
   "download":null|{"file":2,"files":4,"name":"language model","done":B,
                    "total":B,"rate":Bps,"error":null|"text"},
       done/total over all files; kept after a failure with its error,
       null after a cancel or once every file is in place.
   "need":{"download_bytes":B,"disk_free_bytes":B,"ram_bytes":B},
   "genres":[{"id","name","kept":31}, ...],      order of the genres file
   "genre":null|"lofi",                          null until one is picked
   "player":"none"|"playing"|"paused",
   "tune":null|{"n":4|null,"name","bpm","key","length","kept":false,
                "wave":[78 numbers 0..1]},       n null for a kept tune
   "pos":84.0,"pos_at":1795390000.25,  the panel interpolates while playing
   "ready":2,                 new tunes queued behind the playing one
   "kept_playing":false,      the playing tune is a kept one
   "can_next":false,          "next" would play another tune
   "model":{"name","variant","device",
            "state":"unloaded"|"starting"|"idle"|"writing"|"rendering"|
                    "held_game"|"held_memory"|"failed"|"no_device",
            "since":unix,"silence_s":null|39,"detail":null|"text",
            "failures":0,"retry_at":null|unix,
            "ram_used_bytes":null|B,"ram_free_bytes":B},
       ram_used_bytes = the server's RSS plus what the device's VRAM and
       GTT grew by since the server started; null with no server.
   "error":null|"text"}       the first of: the genres file is broken, mpv
                              could not play the last tune (until one plays),
                              hyprctl cannot list the windows (until it can)
  {"event":"error","text":"..."}  to the sender of a malformed line only.

Client -> service: {"cmd":"genre","id":"lofi"} | {"cmd":"toggle"} |
{"cmd":"next"} | {"cmd":"seek","t":61.0} | {"cmd":"load"} | {"cmd":"unload"}
| {"cmd":"retry"} | {"cmd":"download"} | {"cmd":"cancel_download"} |
{"cmd":"refresh"}. A command that does not apply is ignored.

Behaviour:
  genre     picks and plays (the genre already picked: ignored): a kept
            tune of that genre (shuffled, none twice until all have
            played) starts at once if there is one,
            else the playing tune finishes and the first new one follows.
            A different genre cancels the job and drops the old genre's
            queued tunes (their files stay).
  queue     one job at a time while fewer than `ahead` new tunes are
            queued, so a paused player gets the queue filled and no more;
            the model state is "idle" while the queue is full, server or
            not. With no new tune ready, the next is a kept one.
  toggle    pauses or resumes the playing tune; with none playing (after
            a stop or an error) starts the next one, or the first new one
            when it is ready.
  next      goes to the tune after the playing one, new or kept: ignored
            when there is none. The same as MPRIS Next, which mpv's playlist carries.
  a tune    POST /lm {caption, "[Instrumental]", duration, bpm}, polled
            every 0.5 s; the plan's codes (5 a second) are read for the
            silence code: a final run of at least 1 s is cut with a 1.5 s
            fade, any other run over 5 s throws the plan away and the LM
            writes again (silence_s set); a third such plan for one tune is
            a failure. Then POST /synth with the plan, WAV out, ffmpeg trims,
            fades and encodes the MP3 (title, genre, TBPM, TKEY). The
            decoded loudness is checked: a run over 5 s under -50 dB that is
            not the tail discards the tune as a failure.
  unload    cancels the job and stops the server until "load"; kept
            tunes keep playing. Ignored before a genre is picked.
  failure   the job is cancelled and the server stopped; retried after 3 s
            the first time, then every 30 s ("retry" tries now). The count
            resets with the next finished tune. The player is unaffected.
  holds     checked before each job (game and memory), every 10 s while one
            runs (game) and every 30 s while held (both), never while
            unloaded or with no genre: a client of `hyprctl -j clients`
            whose class matches game_class_regex in full (as Hyprland
            matches a rule), or MemAvailable under
            ram_bytes. A hold cancels the job and stops the server; it
            lifts by itself.
  device    at every server start the Vulkan index is resolved from
            `vulkaninfo --summary` by PCI vendor and device id, counting
            GPUs as ggml does (discrete and integrated only, one per device
            UUID), passed as --device Vulkan<N>, and confirmed from the
            server's own "ggml_vulkan: N = <name>" line. Not found or not
            confirmed: state no_device with what was found; no fallback,
            "retry" tries again.
  download  one file at a time into <name>.part, resumed with Range,
            sha256 checked, then renamed; runs with no client attached;
            cancel keeps finished files and the partial one. A download
            asked for right after a cancel waits for the cancelled one to
            stop writing.
  mpv       restarted after it exits, 2 s later, doubling to 60 s while it
            keeps exiting before a tune plays.
  start     a `.<tune file>.part` left in a genre folder by an encode that
            never finished is deleted.
"""

