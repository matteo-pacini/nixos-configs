def serve(args):
    try:
        with open(args.config) as f:
            config = validate_config(json.load(f))
    except OSError:
        raise SystemExit(f"desk-tunes: cannot read the config {args.config}")
    except ValueError as e:
        raise SystemExit(f"desk-tunes: the config is invalid at {e}")
    directory = runtime_dir()
    os.makedirs(directory, mode=0o700, exist_ok=True)
    os.chmod(directory, 0o700)
    path = socket_path()
    if os.path.exists(path):
        probe = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        try:
            probe.connect(path)
            raise SystemExit("desk-tunes: another serve is running")
        except (ConnectionRefusedError, FileNotFoundError):
            os.unlink(path)
        finally:
            probe.close()
    listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    listener.bind(path)
    os.chmod(path, 0o600)
    listener.listen(8)
    listener.setblocking(False)
    service = Service(args, config)
    try:
        service.run(listener)
    finally:
        listener.close()
        try:
            os.unlink(path)
        except FileNotFoundError:
            pass


def attach():
    path = socket_path()
    if not os.path.exists(path):
        sys.stderr.write("the tunes service is not running\n")
        return 3
    sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    try:
        sock.connect(path)
    except OSError as e:
        sys.stderr.write(f"cannot reach the tunes service: {e.strerror}\n")
        return 1
    sel = selectors.DefaultSelector()
    stdin = sys.stdin.buffer.raw if hasattr(sys.stdin.buffer, "raw") else sys.stdin.buffer
    sel.register(stdin, selectors.EVENT_READ, "in")
    sel.register(sock, selectors.EVENT_READ, "sock")
    out = sys.stdout.buffer
    while True:
        for key, _ in sel.select():
            if key.data == "in":
                data = os.read(stdin.fileno(), 65536)
                if not data:
                    return 0
                sock.sendall(data)
            else:
                data = sock.recv(65536)
                if not data:
                    sys.stderr.write("the tunes service closed the connection\n")
                    return 1
                out.write(data)
                out.flush()


def main():
    parser = argparse.ArgumentParser(prog="desk-tunes")
    sub = parser.add_subparsers(dest="mode", required=True)
    s = sub.add_parser("serve")
    s.add_argument("--config", default=CONFIG)
    s.add_argument("--genres")
    for name, default in PROGRAMS.items():
        s.add_argument("--" + name.replace("_", "-"), default=default)
    if TESTING:
        s.add_argument("--test-scale", type=float, default=1.0)
        s.add_argument("--test-ao")
        s.add_argument("--test-meminfo")
        s.add_argument("--test-sysfs")
    sub.add_parser("attach")
    args = parser.parse_args()
    if args.mode == "attach":
        try:
            return attach()
        except (BrokenPipeError, ConnectionResetError):
            return 1
    serve(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
