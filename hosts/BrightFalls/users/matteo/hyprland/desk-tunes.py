def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def validate_config(raw):
    """The config as read, or ValueError naming the first key at fault."""
    def need(cond, key):
        if not cond:
            raise ValueError(key)
    need(isinstance(raw, dict), "(file)")
    m = raw.get("model")
    need(isinstance(m, dict), "model")
    for k in ("name", "variant", "revision", "base_url"):
        need(isinstance(m.get(k), str) and m[k], f"model.{k}")
    files = m.get("files")
    need(isinstance(files, list) and files, "model.files")
    roles = set()
    for i, f in enumerate(files):
        need(isinstance(f, dict), f"model.files[{i}]")
        need(f.get("role") in ROLE_WORDS, f"model.files[{i}].role")
        need(isinstance(f.get("name"), str) and re.fullmatch(r"[A-Za-z0-9._-]+", f["name"])
             and not f["name"].startswith("."), f"model.files[{i}].name")
        need(isinstance(f.get("sha256"), str) and re.fullmatch(r"[0-9a-f]{64}", f["sha256"]),
             f"model.files[{i}].sha256")
        need(is_int(f.get("bytes")) and f["bytes"] > 0, f"model.files[{i}].bytes")
        roles.add(f["role"])
    need(roles == set(ROLE_WORDS), "model.files")
    need(is_int(m.get("silence_code")) and m["silence_code"] >= 0, "model.silence_code")
    need(is_int(m.get("ram_bytes")) and m["ram_bytes"] > 0, "model.ram_bytes")
    d = raw.get("device")
    need(isinstance(d, dict), "device")
    for k in ("vendor", "device"):
        need(isinstance(d.get(k), str) and re.fullmatch(r"0x[0-9a-fA-F]{1,8}", d[k]), f"device.{k}")
    need(isinstance(d.get("label"), str) and d["label"], "device.label")
    need(isinstance(raw.get("game_class_regex"), str), "game_class_regex")
    try:
        re.compile(raw["game_class_regex"])
    except re.error:
        raise ValueError("game_class_regex")
    for k in ("keep", "ahead", "duration"):
        need(is_int(raw.get(k)) and raw[k] > 0, k)
    return raw


def parse_genres(text):
    """The genres list from the file's text, or ValueError with the reason."""
    try:
        raw = json.loads(text)
    except ValueError:
        raise ValueError("not valid JSON")
    if not isinstance(raw, dict) or not isinstance(raw.get("genres"), list) or not raw["genres"]:
        raise ValueError('needs a non-empty "genres" list')
    out, ids, names = [], set(), set()
    for i, g in enumerate(raw["genres"]):
        where = f"genre {i + 1}"
        if not isinstance(g, dict):
            raise ValueError(f"{where} is not an object")
        if not isinstance(g.get("id"), str) or not GENRE_ID.match(g["id"]) or g["id"] in ids:
            raise ValueError(f"{where}: id missing, repeated or not lower-case letters, digits and dashes")
        name = g.get("name")
        if (not isinstance(name, str) or not name.strip() or "/" in name or name.startswith(".")
                or name in names or any(ord(c) < 32 or ord(c) == 127 for c in name)):
            raise ValueError(f"{where}: name missing, repeated, or usable as no folder name")
        if not isinstance(g.get("caption"), str) or not g["caption"].strip():
            raise ValueError(f"{where}: caption missing")
        for key, least in (("turns", 6), ("moods", 8), ("things", 8)):
            v = g.get(key)
            if (not isinstance(v, list) or len(v) < least
                    or not all(isinstance(s, str) and s.strip() for s in v)):
                raise ValueError(f"{where}: {key} needs at least {least} texts")
        if len(set(g["turns"])) < 2:
            raise ValueError(f"{where}: turns needs two different texts")
        b = g.get("bpm")
        if (not isinstance(b, list) or len(b) != 2 or not all(is_int(x) for x in b)
                or not 30 <= b[0] <= b[1] <= 300):
            raise ValueError(f"{where}: bpm must be [low, high] between 30 and 300")
        ids.add(g["id"])
        names.add(name)
        out.append({k: g[k] for k in ("id", "name", "caption", "turns", "bpm", "moods", "things")})
    return out


def caption_for(genre, rng):
    turns = rng.sample(sorted(set(genre["turns"])), 2)
    return f"{genre['caption']}, {turns[0]}, {turns[1]}, instrumental"


def bpm_for(genre, rng):
    return rng.randint(genre["bpm"][0], genre["bpm"][1])


def name_for(genre, rng):
    return f"{rng.choice(genre['moods'])} {rng.choice(genre['things'])}"


def parse_codes(text):
    """The plan's audio codes ("1,2,3," as the LM writes them) as ints."""
    if not isinstance(text, str):
        raise ValueError("no audio codes")
    codes = [int(x) for x in text.split(",") if x.strip()]
    if not codes:
        raise ValueError("no audio codes")
    return codes


def silence_runs(codes, silence):
    """[(start index, length)] of every run of the silence code."""
    runs, start = [], None
    for i, c in enumerate(codes):
        if c == silence:
            if start is None:
                start = i
        elif start is not None:
            runs.append((start, i - start))
            start = None
    if start is not None:
        runs.append((start, len(codes) - start))
    return runs


def plan_verdict(codes, silence, hz=CODE_HZ):
    """{"cut": seconds or None, "rewrite": None or the longest bad run in s}.

    cut: where a final silent run of at least TAIL_MIN starts. rewrite: any
    other run longer than MID_MAX."""
    cut, worst = None, 0.0
    for start, length in silence_runs(codes, silence):
        seconds = length / hz
        if start + length == len(codes) and seconds >= TAIL_MIN:
            cut = start / hz
        elif seconds > MID_MAX:
            worst = max(worst, seconds)
    return {"cut": cut, "rewrite": worst or None}


def retry_delay(failures):
    return RETRY_FIRST if failures <= 1 else RETRY_AFTER


def mpv_restart_delay(exits):
    """Seconds before mpv starts again after `exits` exits in a row."""
    return min(MPV_RESTART_MAX, MPV_RESTART_FIRST * 2 ** (exits - 1))


def key_part(key):
    words = re.findall(r"[A-Za-z0-9#]+", key or "")
    return "-".join(words) or "unknown"


def tune_filename(when, bpm, key):
    return f"{when.strftime('%Y%m%d-%H%M%S')}-{int(bpm)}bpm-{key_part(key)}.mp3"


def parse_tune_filename(name):
    """(bpm, key as written in the name with spaces) or None for other files."""
    m = TUNE_FILE.match(name)
    if not m:
        return None
    return int(m.group(2)), m.group(3).replace("-", " ")


def keep_victims(names, keep, protected):
    """Our files to delete, oldest first, so that `keep` remain.

    Files not matching TUNE_FILE are never counted or returned; protected
    names (playing, queued) are counted but never returned."""
    ours = sorted(n for n in names if TUNE_FILE.match(n))
    excess = len(ours) - keep
    out = []
    for n in ours:
        if excess <= 0:
            break
        if n in protected:
            continue
        out.append(n)
        excess -= 1
    return out


def levels_db(samples, rate=DECODE_RATE, window=LEVEL_WINDOW):
    """RMS level in dBFS of each window of 16-bit mono samples."""
    n = max(1, int(rate * window))
    out = []
    for i in range(0, len(samples), n):
        chunk = samples[i:i + n]
        power = sum(s * s for s in chunk) / len(chunk)
        out.append(-120.0 if power <= 0 else 10 * math.log10(power / (32768.0 ** 2)))
    return out


def quiet_mid_run(levels, window=LEVEL_WINDOW):
    """Seconds of the longest run under QUIET_DB that does not reach the end."""
    worst = run = 0
    for v in levels:
        if v < QUIET_DB:
            run += 1
        else:
            worst = max(worst, run)
            run = 0
    return worst * window


def wave_bars(samples, bars=WAVE_BARS):
    """Mean absolute level of `bars` equal slices, scaled to the loudest."""
    if not samples:
        return [0.0] * bars
    out = []
    n = len(samples)
    for b in range(bars):
        chunk = samples[b * n // bars:(b + 1) * n // bars] or samples[min(n - 1, b * n // bars):][:1]
        out.append(sum(abs(s) for s in chunk) / len(chunk))
    top = max(out)
    return [round(v / top, 3) if top else 0.0 for v in out]


def parse_vulkaninfo(text):
    """Devices of `vulkaninfo --summary`, in its order: dicts of vendor,
    device (lower-case hex), type, name, uuid."""
    devs, cur = [], None
    in_devices = False
    for line in text.splitlines():
        if line.strip() == "Devices:":
            in_devices = True
            continue
        if not in_devices:
            continue
        if re.match(r"^GPU\d+:\s*$", line):
            cur = {}
            devs.append(cur)
            continue
        m = re.match(r"^\s+(\w+)\s*=\s*(.*?)\s*$", line)
        if m and cur is not None:
            cur[m.group(1)] = m.group(2)
    return [{"vendor": d.get("vendorID", "").lower(), "device": d.get("deviceID", "").lower(),
             "type": d.get("deviceType", ""), "name": d.get("deviceName", ""),
             "uuid": d.get("deviceUUID", "")} for d in devs]


def ggml_devices(devs):
    """The devices ggml's Vulkan backend numbers, in its order: discrete and
    integrated GPUs only, the first of any sharing a device UUID."""
    out, seen = [], set()
    for d in devs:
        if d["type"] not in ("PHYSICAL_DEVICE_TYPE_DISCRETE_GPU", "PHYSICAL_DEVICE_TYPE_INTEGRATED_GPU"):
            continue
        if d["uuid"] and d["uuid"] in seen:
            continue
        seen.add(d["uuid"])
        out.append(d)
    return out


def resolve_device(text, vendor, device):
    """(index, name) of the wanted device, or (None, what was found)."""
    vendor, device = vendor.lower(), device.lower()
    gpus = ggml_devices(parse_vulkaninfo(text))
    for i, d in enumerate(gpus):
        if d["vendor"] == vendor and d["device"] == device:
            return i, d["name"]
    if not gpus:
        return None, "found no Vulkan GPU"
    names = "; ".join(d["name"] for d in gpus)
    return None, f"found {len(gpus)} other Vulkan GPU{'s' if len(gpus) > 1 else ''}: {names}"


def confirm_device(lines, index, name):
    """None when the server's ggml_vulkan line for `index` names `name`, else
    what it said instead."""
    listed = {}
    for line in lines:
        m = GGML_DEVICE.match(line)
        if m:
            listed[int(m.group(1))] = m.group(2)
    if index in listed and listed[index].startswith(name):
        return None
    if index in listed:
        return f"the server's Vulkan{index} is {listed[index].split(' | ')[0]}"
    return f"the server listed no Vulkan{index}"


def game_running(clients, pattern):
    if not pattern:
        return False
    rx = re.compile(pattern)
    return any(isinstance(c, dict) and isinstance(c.get("class"), str) and rx.fullmatch(c["class"])
               for c in clients if isinstance(clients, list))


def mem_available(text):
    m = re.search(r"^MemAvailable:\s+(\d+) kB", text, re.M)
    return int(m.group(1)) * 1024 if m else None


def multipart_audio(body):
    """The first audio part of ace-server's multipart/mixed synth result."""
    if not body.startswith(b"--"):
        raise ValueError("not multipart")
    boundary = body[:body.index(b"\r\n")]
    for part in body.split(b"\r\n" + boundary):
        part = part[len(boundary):] if part.startswith(boundary) else part
        head, sep, data = part.partition(b"\r\n\r\n")
        if sep and b"content-type: audio/" in head.lower():
            return data
    raise ValueError("no audio part")


def need_bytes(files, present):
    """Bytes still to download, given {name: bytes on disk (final or part)}."""
    return sum(max(0, f["bytes"] - present.get(f["name"], 0)) for f in files)


